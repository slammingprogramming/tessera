// Regenerates the Lua test fixtures under tests/fixtures/:
//   deflate_fixtures.lua  raw-DEFLATE streams produced by Node's zlib in each block style, with the SHA-256 of the
//                         original data so the Lua decoder can be verified without embedding the plain data
//   bundle_fixtures.lua   an offline bundle in both delivery forms (file drop + pasted chunk lines)
//   node tools/test/gen-fixtures.mjs
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { deflateRawSync, constants } from 'node:zlib';
import { root } from '../lib/craftos.mjs';
import { KIND, buildContainer, toChunks, toFile } from '../lib/bundle.mjs';

const NL = '\n';
const sha = (b) => createHash('sha256').update(b).digest('hex');
const HEADER = '-- SPDX-License-Identifier: AGPL-3.0-or-later' + NL + '-- GENERATED by tools/test/gen-fixtures.mjs - do not edit.' + NL;

function rng(seed) { // mulberry32, deterministic
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(1234);
const randomBytes = (n) => Buffer.from(Array.from({ length: n }, () => Math.floor(rand() * 256)));

const luaish = Array.from({ length: 200 }, (_, i) =>
  `local function handler_${i}(a, b) if a > ${i} then return b .. "item ${i}" end return #b + ${i * 7} end`).join(NL);
const chunk = randomBytes(40000);

// ---- deflate fixtures -------------------------------------------------------------------------------------------
const cases = [
  ['empty', Buffer.alloc(0), {}],
  ['fixed-huffman', Buffer.from('hello hello hello hello, tessera tessera tessera'), { strategy: constants.Z_FIXED }],
  ['dynamic-huffman text', Buffer.from(luaish), { level: 9 }],
  ['stored block', randomBytes(3000), { level: 0 }],
  ['far back-references', Buffer.concat([chunk, chunk, chunk.subarray(0, 1234)]), { level: 9 }],
  ['run of one byte', Buffer.alloc(70000, 0x61), { level: 6 }],
  ['all byte values', Buffer.from(Array.from({ length: 512 }, (_, i) => i % 256)), { level: 9 }],
];

let lua = HEADER + 'return {' + NL;
for (const [name, data, opts] of cases) {
  const z = deflateRawSync(data, opts);
  lua += `  { name = ${JSON.stringify(name)}, len = ${data.length}, sha = "${sha(data)}",${NL}`;
  lua += `    b64 = "${z.toString('base64')}" },${NL}`;
}
lua += '}' + NL;
mkdirSync(join(root, 'tests', 'fixtures'), { recursive: true });
writeFileSync(join(root, 'tests', 'fixtures', 'deflate_fixtures.lua'), lua);
console.log(`wrote ${cases.length} deflate fixtures (${lua.length} bytes)`);

// ---- offline bundle fixture ---------------------------------------------------------------------------------------
const blobs = ['print("hello from blob one")' + NL, 'return { two = true }' + NL, luaish.slice(0, 3000)];
blobs[0] = blobs[0].repeat(40);
const entries = [
  { kind: KIND.index, name: 'index', data: JSON.stringify({ format: 1, packages: { demo: { version: '1.0.0' } } }) },
  { kind: KIND.package, name: 'demo', data: JSON.stringify({ name: 'demo', latest: '1.0.0', versions: {} }) },
  ...blobs.map((b) => ({ kind: KIND.blob, name: sha(b), data: b })),
];
const container = buildContainer(entries);
const { id, lines } = toChunks(container, 120);
let bl = HEADER + 'return {' + NL;
bl += `  id = "${id}",${NL}`;
bl += `  blobs = { ${blobs.map((b) => `"${sha(b)}"`).join(', ')} },${NL}`;
bl += `  file_b64 = "${toFile(container).toString('base64')}",${NL}`;
bl += `  lines = {${NL}${lines.map((l) => `    "${l}",`).join(NL)}${NL}  },${NL}}${NL}`;
writeFileSync(join(root, 'tests', 'fixtures', 'bundle_fixtures.lua'), bl);
console.log(`wrote bundle fixture: ${lines.length} chunk lines`);
