// Generates tests/fixtures/tz_vectors.lua: for every zone in src/ntp/.../time.lua, the real UTC offset (from Node's ICU time zone
// database) at many instants of 2024-2030, including both sides of every daylight-saving transition, so the Lua rules are checked
// against the real database.
//   node tools/test/gen-tz-fixtures.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from '../lib/craftos.mjs';

const src = readFileSync(join(root, 'src', 'ntp', 'root', 'sys', 'lib', 'tsr', 'time.lua'), 'utf8');
const zones = [...src.matchAll(/\["([A-Za-z_\/]+)"\] = \{ -?\d+, "/g)].map((m) => m[1]).filter((z) => z !== 'GMT' && z !== 'UTC' && z !== 'Etc/UTC');

const fmtCache = new Map();
function offsetMinutes(zone, ms) {
  let f = fmtCache.get(zone);
  if (!f) {
    f = new Intl.DateTimeFormat('en-US', { timeZone: zone, hourCycle: 'h23', year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric', second: 'numeric' });
    fmtCache.set(zone, f);
  }
  const p = Object.fromEntries(f.formatToParts(new Date(ms)).map((x) => [x.type, x.value]));
  const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour, +p.minute, +p.second);
  return Math.round((asUtc - Math.floor(ms / 1000) * 1000) / 60000);
}

const start = Date.UTC(2024, 0, 1), end = Date.UTC(2031, 0, 1);
const DAY = 86400000;
const lines = ['-- SPDX-License-Identifier: AGPL-3.0-or-later', '-- GENERATED by tools/test/gen-tz-fixtures.mjs - do not edit. Offsets from Node ICU.', 'return {'];
let count = 0;
for (const zone of zones) {
  const points = new Set();
  let prev = offsetMinutes(zone, start);
  for (let t = start; t < end; t += DAY) {
    const here = offsetMinutes(zone, t + DAY);
    if (new Date(t).getUTCDate() === 15 && new Date(t).getUTCMonth() % 3 === 0) points.add(t + 12 * 3600000);        // one ordinary instant per month
    if (here !== prev) {                       // a transition inside (t, t + DAY]: bisect to the second
      let lo = t, hi = t + DAY;
      while (hi - lo > 1000) { const mid = Math.floor((lo + hi) / 2000) * 1000; if (offsetMinutes(zone, mid) === prev) lo = mid; else hi = mid; }
      points.add(hi - 1000); points.add(hi); points.add(hi + 3600000);
    }
    prev = here;
  }
  const keep = [...points].sort((a, b) => a - b);
  lines.push(`  { zone = "${zone}", points = {`);
  for (const ms of keep) { lines.push(`    { ${ms / 1000}, ${offsetMinutes(zone, ms)} },`); count++; }
  lines.push('  } },');
}
lines.push('}');
writeFileSync(join(root, 'tests', 'fixtures', 'tz_vectors.lua'), lines.join('\n') + '\n');
console.log(`wrote tests/fixtures/tz_vectors.lua: ${zones.length} zones, ${count} points`);
