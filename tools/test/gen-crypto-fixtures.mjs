// Generates tests/fixtures/crypto_vectors.lua: reference outputs for the Lua cryptography, computed with Node's crypto module
// (OpenSSL) so the pure-Lua implementations are checked against an independent implementation, plus the RFC test inputs.
//   node tools/test/gen-crypto-fixtures.mjs
import { createCipheriv, createHash, createPrivateKey, createPublicKey, diffieHellman, hkdfSync, pbkdf2Sync, sign } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from '../lib/craftos.mjs';
import { keyId, signText } from '../lib/sign.mjs';

const hex = (b) => Buffer.from(b).toString('hex');
const unhex = (h) => Buffer.from(h, 'hex');

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const r = rng(20261001);
const bytes = (n) => Buffer.from(Array.from({ length: n }, () => Math.floor(r() * 256)));

const PKCS8_ED = unhex('302e020100300506032b657004220420');
const PKCS8_X = unhex('302e020100300506032b656e04220420');
const SPKI_X = unhex('302a300506032b656e032100');
const edPriv = (seed) => createPrivateKey({ key: Buffer.concat([PKCS8_ED, seed]), format: 'der', type: 'pkcs8' });
const edPub = (seed) => createPublicKey(edPriv(seed)).export({ format: 'der', type: 'spki' }).subarray(-32);
const xPriv = (sk) => createPrivateKey({ key: Buffer.concat([PKCS8_X, sk]), format: 'der', type: 'pkcs8' });
const xPub = (sk) => createPublicKey(xPriv(sk)).export({ format: 'der', type: 'spki' }).subarray(-32);
const xPubKey = (pk) => createPublicKey({ key: Buffer.concat([SPKI_X, pk]), format: 'der', type: 'spki' });

const out = [];
const add = (s) => out.push(s);
add('-- SPDX-License-Identifier: AGPL-3.0-or-later');
add('-- GENERATED by tools/test/gen-crypto-fixtures.mjs - do not edit. Reference values from Node (OpenSSL).');
add('return {');

// sha512
add('  sha512 = {');
for (const len of [0, 1, 3, 111, 112, 113, 127, 128, 129, 255, 256, 1000]) {
  const msg = len === 3 ? Buffer.from('abc') : Buffer.from(Array.from({ length: len }, (_, i) => (i * 7 + 3) % 256));
  add(`    { len = ${len}, msg = "${hex(msg)}", digest = "${createHash('sha512').update(msg).digest('hex')}" },`);
}
add('  },');

// ed25519 (RFC 8032 seeds first, then random ones)
const edSeeds = ['9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60', '4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb',
  'c5aa8df43f9f837bedb7442f31dcb7b166d38535076f094b85ce3a2e0b4458f7'].map(unhex);
for (let i = 0; i < 5; i++) edSeeds.push(bytes(32));
const edMsgs = [Buffer.alloc(0), unhex('72'), unhex('af82'), bytes(40), bytes(100), Buffer.from('tessera'), bytes(1), bytes(200)];
add('  ed25519 = {');
edSeeds.forEach((seed, i) => {
  const msg = edMsgs[i];
  add(`    { seed = "${hex(seed)}", pub = "${hex(edPub(seed))}", msg = "${hex(msg)}", sig = "${hex(sign(null, msg, edPriv(seed)))}" },`);
});
add('  },');

// x25519
add('  x25519 = {');
for (let i = 0; i < 5; i++) {
  const a = bytes(32), b = bytes(32);
  const shared = diffieHellman({ privateKey: xPriv(a), publicKey: xPubKey(xPub(b)) });
  add(`    { a = "${hex(a)}", apub = "${hex(xPub(a))}", b = "${hex(b)}", bpub = "${hex(xPub(b))}", shared = "${hex(shared)}" },`);
}
add('  },');

// chacha20-poly1305
add('  aead = {');
for (const [len, aadLen] of [[0, 0], [1, 0], [15, 3], [16, 16], [17, 5], [63, 0], [64, 12], [65, 1], [300, 20], [1000, 0]]) {
  const key = bytes(32), nonce = bytes(12), plain = bytes(len), aad = bytes(aadLen);
  const c = createCipheriv('chacha20-poly1305', key, nonce, { authTagLength: 16 });
  c.setAAD(aad, { plaintextLength: len });
  const ct = Buffer.concat([c.update(plain), c.final()]);
  add(`    { key = "${hex(key)}", nonce = "${hex(nonce)}", plain = "${hex(plain)}", aad = "${hex(aad)}", sealed = "${hex(Buffer.concat([ct, c.getAuthTag()]))}" },`);
}
add('  },');

// kdf
add('  hkdf = {');
for (const [ikm, salt, info, len] of [[bytes(22), bytes(13), bytes(10), 42], [bytes(32), Buffer.alloc(0), Buffer.from('tessera'), 64], [bytes(5), bytes(40), Buffer.alloc(0), 33]]) {
  add(`    { ikm = "${hex(ikm)}", salt = "${hex(salt)}", info = "${hex(info)}", len = ${len}, okm = "${hex(Buffer.from(hkdfSync('sha256', ikm, salt, info, len)))}" },`);
}
add('  },');
add('  pbkdf2 = {');
for (const [pw, salt, iter, len] of [['password', 'salt', 1, 32], ['password', 'salt', 2, 32], ['correct horse', 'tessera salt', 50, 40], ['pw', 'NaCl', 100, 20]]) {
  add(`    { password = "${pw}", salt = "${salt}", iter = ${iter}, len = ${len}, dk = "${hex(pbkdf2Sync(pw, salt, iter, len, 'sha256'))}" },`);
}
add('  },');
// a registry document signed by the build tooling (tools/lib/sign.mjs), to be verified by the Lua side
{
  const seed = hex(bytes(32));
  const pub = hex(edPub(unhex(seed)));
  const text = JSON.stringify({ format: 1, serial: 1700000000, packages: { core: { version: '1.0.0', docSha256: 'ab'.repeat(32) } } });
  const key = { seed, public: pub, keyid: keyId(pub) };
  add(`  registry = { seed = "${seed}", public = "${pub}", keyid = "${key.keyid}", text = ${JSON.stringify(text)}, sig = ${JSON.stringify(signText(key, text))}, trustSig = ${JSON.stringify(signText(key, text, 'registry-trust'))} },`);
}
add('}');

mkdirSync(join(root, 'tests', 'fixtures'), { recursive: true });
writeFileSync(join(root, 'tests', 'fixtures', 'crypto_vectors.lua'), out.join('\n') + '\n');
console.log('wrote tests/fixtures/crypto_vectors.lua');
