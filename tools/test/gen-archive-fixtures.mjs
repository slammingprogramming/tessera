// Generates tests/fixtures/archive_fixtures.lua: a tar made by an independent writer (here, Node), gzip files made by zlib (levels 1, 6, 9
// and one with a file name in the header), so the Lua code is checked against real implementations.
//   node tools/test/gen-archive-fixtures.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync, deflateRawSync, crc32 } from 'node:zlib';
import { root } from '../lib/craftos.mjs';

function tarHeader(name, size, type) {
  const h = Buffer.alloc(512);
  let prefix = '';
  if (name.length > 100) {
    const cut = name.lastIndexOf('/', 155);
    prefix = name.slice(0, cut);
    name = name.slice(cut + 1);
  }
  h.write(name, 0, 'latin1');
  h.write('0000644\0', 100, 'latin1');
  h.write('0000000\0', 108, 'latin1');
  h.write('0000000\0', 116, 'latin1');
  h.write(size.toString(8).padStart(11, '0') + '\0', 124, 'latin1');
  h.write('14000000000\0', 136, 'latin1');
  h.write('        ', 148, 'latin1');
  h.write(type, 156, 'latin1');
  h.write('ustar\0' + '00', 257, 'latin1');
  h.write(prefix, 345, 'latin1');
  let sum = 0;
  for (const b of h) sum += b;
  h.write(sum.toString(8).padStart(6, '0') + '\0 ', 148, 'latin1');
  return h;
}

function tar(entries) {
  const parts = [];
  for (const e of entries) {
    const data = e.data ?? Buffer.alloc(0);
    parts.push(tarHeader(e.name, e.dir ? 0 : data.length, e.dir ? '5' : '0'));
    if (!e.dir) {
      parts.push(data);
      if (data.length % 512) parts.push(Buffer.alloc(512 - (data.length % 512)));
    }
  }
  parts.push(Buffer.alloc(1024));
  return Buffer.concat(parts);
}

const text = Buffer.from(Array.from({ length: 200 }, (_, i) => `line ${i}: the quick brown fox jumps over the lazy dog ${i * 7919 % 1000}`).join('\n'));
const longDir = 'a-rather-long-directory-name-to-need-the-prefix-field/'.repeat(2) + 'deep';
const entries = [
  { name: 'project/', dir: true },
  { name: 'project/readme.txt', data: Buffer.from('hello from a real tar\n') },
  { name: 'project/empty.bin', data: Buffer.alloc(0) },
  { name: 'project/text.txt', data: text },
  { name: 'project/binary.bin', data: Buffer.from(Array.from({ length: 700 }, (_, i) => (i * 37) % 256)) },
];
const tarBytes = tar(entries);
const longTar = tar([{ name: longDir + '/file.txt', data: Buffer.from('long path') }]);   // listed only: the host file system limits long paths

function lit(buf) {
  return '"' + [...buf].map((b) => '\\' + String(b).padStart(3, '0')).join('') + '"';
}

function gzipNamed(data, name) {
  const raw = deflateRawSync(data, { level: 6 });
  const head = Buffer.concat([Buffer.from([0x1f, 0x8b, 8, 8, 0, 0, 0, 0, 0, 3]), Buffer.from(name + '\0', 'latin1')]);
  const tail = Buffer.alloc(8);
  tail.writeUInt32LE(crc32 ? crc32(data) : 0, 0);
  tail.writeUInt32LE(data.length, 4);
  return Buffer.concat([head, raw, tail]);
}

const out = ['-- SPDX-License-Identifier: AGPL-3.0-or-later', '-- GENERATED by tools/test/gen-archive-fixtures.mjs - do not edit.', 'return {'];
out.push(`  tar = ${lit(tarBytes)},`);
out.push(`  longtar = ${lit(longTar)},`);
out.push(`  text = ${lit(text)},`);
out.push(`  tgz = ${lit(gzipSync(tarBytes, { level: 6 }))},`);
out.push('  gz = {');
for (const level of [1, 6, 9]) out.push(`    { level = ${level}, bytes = ${lit(gzipSync(text, { level }))} },`);
out.push('  },');
out.push(`  named = ${lit(gzipNamed(text, 'text.txt'))},`);
out.push('}');
writeFileSync(join(root, 'tests', 'fixtures', 'archive_fixtures.lua'), out.join('\n') + '\n');
console.log(`wrote tests/fixtures/archive_fixtures.lua (${tarBytes.length} byte tar)`);
