// Generates tests/fixtures/diff_fixtures.lua: pairs of texts with the unified diff that git itself makes for them, so the Lua parser
// and patcher are checked against a real implementation.
//   node tools/test/gen-diff-fixtures.mjs
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { root } from '../lib/craftos.mjs';

const lines = (n, f) => Array.from({ length: n }, (_, i) => f(i)).join('\n') + '\n';
const base = lines(40, (i) => `line ${i + 1} of the base text`);
const cases = {
  middle: [base, base.replace('line 20 of', 'LINE twenty of')],
  startEnd: [base, 'new first line\n' + base + 'new last line\n'],
  multi: [base, base.replace('line 5 of', 'five').replace('line 30 of', 'thirty').replace('line 31 of the base text\n', '')],
  noeolAdd: ['one\ntwo\nthree\n', 'one\ntwo\nthree'],
  noeolRemove: ['one\ntwo\nthree', 'one\ntwo\nthree\n'],
  noeolChange: ['one\ntwo\nthree', 'one\ntwo\nthree four'],
  deleteAll: ['a\nb\nc\n', ''],
  fromEmpty: ['', 'a\nb\nc\n'],
  reorder: ['alpha\nbeta\ngamma\ndelta\nepsilon\n', 'alpha\ndelta\ngamma\nbeta\nepsilon\n'],
  repeated: ['x\nx\nx\ny\nx\nx\n', 'x\nx\ny\nx\nx\nx\nz\n'],
};

const dir = mkdtempSync(join(tmpdir(), 'tsr-diff-'));
const esc = (s) => '"' + [...Buffer.from(s, 'utf8')].map((b) => '\\' + String(b).padStart(3, '0')).join('') + '"';
const out = ['-- SPDX-License-Identifier: AGPL-3.0-or-later', '-- GENERATED by tools/test/gen-diff-fixtures.mjs - do not edit.', 'return {'];
try {
  for (const [name, [a, b]] of Object.entries(cases)) {
    writeFileSync(join(dir, 'a'), a);
    writeFileSync(join(dir, 'b'), b);
    const r = spawnSync('git', ['diff', '--no-index', '--no-color', '--no-prefix', '-U3', 'a', 'b'], { cwd: dir, encoding: 'utf8' });
    if (r.status !== 1 && r.status !== 0) throw new Error('git diff failed: ' + r.stderr);
    out.push(`  ${name} = { a = ${esc(a)}, b = ${esc(b)}, patch = ${esc(r.stdout)} },`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
out.push('}');
writeFileSync(join(root, 'tests', 'fixtures', 'diff_fixtures.lua'), out.join('\n') + '\n');
console.log(`wrote tests/fixtures/diff_fixtures.lua (${Object.keys(cases).length} cases)`);
