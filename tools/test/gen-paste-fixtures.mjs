// Generates tests/fixtures/paste_fixtures.lua: a Pastebin mirror as the paste manager makes it (a fake Pastebin holding every paste), with long files split over
// several pastes, a binary file in base64 and a snapshot that is itself in several pastes, so the Lua clients are checked against the real producer.
//   node tools/test/gen-paste-fixtures.mjs
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { root } from '../lib/craftos.mjs';
import * as P from '../lib/pastes.mjs';

const sha = (b) => createHash('sha256').update(b).digest('hex');
const dir = mkdtempSync(join(tmpdir(), 'tsr-pastefix-'));
const site = join(dir, 'site');
mkdirSync(join(site, 'registry', 'packages'), { recursive: true });
mkdirSync(join(site, 'blobs'), { recursive: true });

const lines = (n) => Array.from({ length: n }, (_, i) => `-- generated line ${i + 1} of a long program\n`).join('');
const files = {
  core: { '/sys/boot.lua': '-- boot\nreturn "boot"\n', '/sys/long.lua': lines(120), '/sys/data.bin': Buffer.from(Array.from({ length: 700 }, (_, i) => (i * 13 + 5) % 256)) },
  pkg: { '/sys/pkg.lua': '-- pkg\nreturn "pkg"\n' },
};
const index = { format: 1, packages: {} };
const expected = { blobs: {}, docs: {} };
for (const [name, fl] of Object.entries(files)) {
  const list = [];
  for (const [path, content] of Object.entries(fl)) {
    const b = Buffer.from(content);
    writeFileSync(join(site, 'blobs', sha(b)), b);
    list.push({ path, sha256: sha(b), size: b.length });
    expected.blobs[path] = sha(b);
  }
  const doc = { name, latest: '1.0.0', versions: { '1.0.0': { name, version: '1.0.0', requires: {}, files: list } } };
  writeFileSync(join(site, 'registry', 'packages', `${name}.json`), JSON.stringify(doc));
  index.packages[name] = { version: '1.0.0' };
}
writeFileSync(join(site, 'registry', 'index.json'), JSON.stringify(index));
writeFileSync(join(site, 'registry', 'index.json.sig'), 'SIGNATURE-FOR-THE-TEST==');
writeFileSync(join(site, 'install.lua'), '-- installer\n');

// a minimal in-memory Pastebin
const pastes = {};
let n = 0;
const api = { create: async ({ text }) => { const id = 'f' + (++n).toString(36).padStart(4, '0'); pastes[id] = text; return id; } };
const state = P.emptyState();
const ctx = { api, state, limit: 1000, delay: 0, chunk: 300, sleep: async () => {} };
const p = P.plan(site, { chunk: 300 });
await P.sync(p, ctx);
const { snapshot } = P.buildSnapshot(p, state);
const snapText = JSON.stringify(snapshot);
// the snapshot itself is cut into several pastes, as it would be if it grew past the limit
const parts = [];
for (let i = 0; i < snapText.length; i += 200) parts.push(snapText.slice(i, i + 200));
const snapIds = [];
for (const t of parts) snapIds.push(await api.create({ text: t }));
const q = (s) => '"' + [...Buffer.from(s, 'utf8')].map((b) => '\\' + String(b).padStart(3, '0')).join('') + '"';
const out = ['-- SPDX-License-Identifier: AGPL-3.0-or-later', '-- GENERATED by tools/test/gen-paste-fixtures.mjs - do not edit.', 'return {', '  pastes = {'];
for (const [id, text] of Object.entries(pastes)) out.push(`    [${q(id)}] = ${q(text)},`);
out.push('  },', `  snapshot = ${q(snapIds.join('+'))},`, `  longSha = ${q(expected.blobs['/sys/long.lua'])},`, `  dataSha = ${q(expected.blobs['/sys/data.bin'])},`, `  bootSha = ${q(expected.blobs['/sys/boot.lua'])},`);
out.push(`  longRef = ${q(snapshot.blobs[expected.blobs['/sys/long.lua']])},`, `  dataRef = ${q(snapshot.blobs[expected.blobs['/sys/data.bin']])},`);
out.push(`  indexText = ${q(JSON.stringify(index))},`, '}');
const target = join(root, 'tests', 'fixtures', 'paste_fixtures.lua');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out.join('\n') + '\n') { console.error('tests/fixtures/paste_fixtures.lua is out of date: run node tools/test/gen-paste-fixtures.mjs'); process.exit(1); }
  console.log('paste fixtures are current');
  process.exit(0);
}
writeFileSync(target, out.join('\n') + '\n');
console.log(`wrote tests/fixtures/paste_fixtures.lua (${Object.keys(pastes).length + snapIds.length} pastes, snapshot in ${snapIds.length} parts)`);
