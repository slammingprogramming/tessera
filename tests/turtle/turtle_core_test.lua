local Sim = dofile("/tests/lib/turtlesim.lua")
local T = require("tsr.turtle")
local vfs = require("tsr.vfs")

local DIR = "/tmp-turtle"

local function fresh(opts)
  if fs.exists(DIR) then fs.delete(DIR) end
  T.dir = DIR
  T.sleep = function() end
  T.unloadForTest()
  local sim = Sim.new(opts)
  sim:install()
  return sim
end

local function done(sim)
  sim:uninstall()
  if fs.exists(DIR) then fs.delete(DIR) end
end

test("position and heading follow moves and turns", function()
  local sim = fresh()
  ok(T.forward() and T.forward())
  T.turnRight()
  ok(T.forward())
  ok(T.up())
  ok(T.back())
  eq({ T.pos() }, { 0, 1, -2, 1 }, "tsr.turtle frame")
  eq({ sim:where() }, { 0, 1, -2, 1 }, "sim agrees")
  done(sim)
end)

test("face() takes the shortest turn", function()
  local sim = fresh()
  T.face(3)
  eq(sim.dir, 3)
  T.face(1)
  eq(sim.dir, 1)
  T.face(1)
  T.turnAround()
  eq(sim.dir, 3)
  done(sim)
end)

test("state survives a restart", function()
  local sim = fresh()
  T.forward() T.forward() T.turnLeft() T.down()
  T.unloadForTest()
  eq({ T.pos() }, { 0, -1, -2, 3 })
  done(sim)
end)

test("a move interrupted by a restart is settled by the fuel level", function()
  local sim = fresh({ fuel = 100 })
  T.forward()
  -- pretend the turtle was unloaded right after the request: journal says fuel 99 before the next forward
  local st = T.state()
  st.pending = { op = "f", fuel = 99 }
  vfs.writeTable(DIR .. "/pos.9", st) -- not a valid slot name; ignored
  -- write a real slot file with a higher sequence number
  local h = fs.open(DIR .. "/pos." .. ((st.seq + 1) % 2), "w")
  local copy = { x = st.x, y = st.y, z = st.z, dir = st.dir, seq = st.seq + 1, pending = { op = "f", fuel = 99 } }
  h.write(textutils.serialize(copy))
  h.close()
  -- case A: the move happened (fuel went 99 -> 98)
  sim.fuel = 98
  T.unloadForTest()
  eq({ T.pos() }, { 0, 0, -2, 0 })
  -- case B: the move did not happen (fuel unchanged)
  local copy2 = { x = 0, y = 0, z = -2, dir = 0, seq = 50, pending = { op = "f", fuel = 98 } }
  h = fs.open(DIR .. "/pos.0", "w")
  h.write(textutils.serialize(copy2))
  h.close()
  T.unloadForTest()
  eq({ T.pos() }, { 0, 0, -2, 0 })
  done(sim)
end)

test("a corrupt slot file falls back to the other slot", function()
  local sim = fresh()
  T.forward()
  T.forward()
  local h = fs.open(DIR .. "/pos.1", "w") h.write("{{garbage") h.close()
  h = fs.open(DIR .. "/pos.0", "w") h.write("{{garbage") h.close()
  T.unloadForTest()
  eq({ T.pos() }, { 0, 0, 0, 0 }, "both slots unreadable -> fresh frame, no crash")
  done(sim)
end)

test("failed moves do not change the position", function()
  local sim = fresh()
  sim:set(0, 0, -1, "minecraft:stone")
  local okMove, err = T.forward()
  ok(not okMove and err)
  eq({ T.pos() }, { 0, 0, 0, 0 })
  done(sim)
end)

test("digMove clears blocks, fights mobs and reports unbreakable blocks", function()
  local sim = fresh()
  sim:set(0, 0, -1, "minecraft:stone")
  ok(T.digMove("f"))
  eq({ T.pos() }, { 0, 0, -1, 0 })
  eq(sim:itemCount("minecraft:cobblestone"), 1)
  sim:addMob(0, 0, -2, 2)
  ok(T.digMove("f"))
  eq(sim.kills, 2)
  sim:set(0, 0, -3, "minecraft:bedrock")
  local okBed, why = T.digMove("f", { tries = 3 })
  ok(not okBed and why:find("unbreakable"))
  sim:set(0, 1, -2, "minecraft:dirt")
  ok(T.digMove("u"))
  eq(select(2, T.pos()), 1)
  done(sim)
end)

test("digMove stops when out of fuel", function()
  local sim = fresh({ fuel = 0 })
  local okMove, why = T.digMove("f")
  ok(not okMove)
  eq(why, "Out of fuel")
  done(sim)
end)

test("goto walks to coordinates, digging only when asked", function()
  local sim = fresh()
  sim:fill(2, 0, -3, 2, 0, -3, "minecraft:stone")
  local okWalk, err = T.goto(2, 0, -3)
  ok(okWalk == false and err, "obstructed without dig")
  local x, y, z = T.pos()
  ok(not (x == 2 and z == -3))
  ok(T.goto(2, 0, -3, { dig = true }))
  eq({ T.pos() }, { 2, 0, -3, T.state().dir })
  ok(T.goto(0, 2, 0, { dig = true }))
  eq({ sim:where() }, { 0, 2, 0, sim.dir })
  eq(T.distanceTo(3, 2, 4), 7)
  done(sim)
end)

test("ensureFuel burns fuel items, keeps protected slots, and reports shortage", function()
  local sim = fresh({ fuel = 10 })
  sim:give("minecraft:coal", 4, 5)
  sim:give("minecraft:coal", 4, 6)
  ok(T.ensureFuel(50, { keep = { [6] = true } }))
  eq(sim.fuel, 90) -- one coal (80) burned, just enough
  eq(sim:itemCount("minecraft:coal"), 7)
  local okFuel, why = T.ensureFuel(5000, { keep = { [6] = true } })
  ok(not okFuel and why:find("need 5000"))
  eq(sim.inv[6].count, 4, "protected slot untouched")
  done(sim)
end)

test("unlimited fuel is treated as plenty", function()
  local sim = fresh({ unlimited = true })
  ok(T.ensureFuel(1000000))
  eq(T.fuel(), math.huge)
  T.forward()
  eq({ T.pos() }, { 0, 0, -1, 0 })
  done(sim)
end)

test("inventory helpers", function()
  local sim = fresh()
  sim:give("minecraft:torch", 10, 3)
  sim:give("minecraft:stone", 5, 7)
  sim:give("minecraft:torch", 4, 9)
  eq(T.slotOf("minecraft:torch"), 3)
  eq(T.slotOf("minecraft:*"), 3)
  eq(T.slotOf({ "minecraft:stone" }), 7)
  eq(T.countItems("minecraft:torch"), 14)
  eq(T.slotOf("minecraft:nothing"), nil)
  eq(T.selectItem("minecraft:stone"), 7)
  eq(sim.selected, 7)
  eq(T.emptySlots(), 13)
  ok(T.slotOf(function(d) return d.count == 5 end) == 7)
  done(sim)
end)

test("dump empties the inventory into a chest but keeps what it is told to", function()
  local sim = fresh()
  sim:set(0, -1, 0, "minecraft:chest")
  sim:give("minecraft:cobblestone", 30, 2)
  sim:give("minecraft:torch", 8, 1)
  sim:give("minecraft:coal", 3, 4)
  local stacks = T.dump("d", { [1] = true }, "minecraft:coal")
  eq(stacks, 1)
  eq(sim:chestCount(0, -1, 0, "minecraft:cobblestone"), 30)
  eq(sim:itemCount("minecraft:torch"), 8)
  eq(sim:itemCount("minecraft:coal"), 3)
  done(sim)
end)

test("jobs: begin, update, resumable, finish", function()
  local sim = fresh()
  eq(T.job.get(), nil)
  T.job.begin("bore", { length = 10 }, { "bore", "10" })
  T.job.update({ step = 3 })
  local j = T.job.resumable("bore", { length = 10 })
  ok(j and j.progress.step == 3)
  eq(T.job.resumable("bore", { length = 11 }), nil, "different parameters do not resume")
  eq(T.job.resumable("room", { length = 10 }), nil)
  T.job.finish()
  eq(T.job.get(), nil)
  done(sim)
end)

test("GPS calibration adopts absolute coordinates and heading", function()
  local sim = fresh()
  local realGps = rawget(_G, "gps")
  -- world position = sim position + (100, 64, 200); the turtle actually faces east in the sim
  sim.dir = 1
  _G.gps = { locate = function() return sim.x + 100, sim.y + 64, sim.z + 200 end }
  local okCal, err = T.calibrate()
  _G.gps = realGps
  ok(okCal, tostring(err))
  eq({ T.pos() }, { 100, 64, 200, 1 })
  eq({ sim.x, sim.dir }, { 0, 1 }, "turtle ends where it started")
  done(sim)
end)

test("GPS calibration fails cleanly without a signal", function()
  local sim = fresh()
  local realGps = rawget(_G, "gps")
  _G.gps = { locate = function() return nil end }
  local okCal, err = T.calibrate()
  _G.gps = realGps
  ok(not okCal and err:find("GPS"))
  done(sim)
end)
