local vfs = require("tsr.vfs")

local function cleanup(...)
  for _, p in ipairs({ ... }) do if fs.exists(p) then fs.delete(p) end end
end

test("path helpers", function()
  eq(vfs.normalize("a//b/../c"), "/a/c")
  eq(vfs.normalize("/"), "/")
  eq(vfs.join("/a", "b", "../c"), "/a/c")
  eq(vfs.dirname("/a/b/c"), "/a/b")
  eq(vfs.dirname("/a"), "/")
  eq(vfs.basename("/a/b.lua"), "b.lua")
end)

test("atomic write round trip, overwrite, binary", function()
  local p = "/tmp-vfs/dir/file.txt"
  ok(vfs.writeFile(p, "one"))
  eq(vfs.readFile(p), "one")
  ok(vfs.writeFile(p, "two"))
  eq(vfs.readFile(p), "two")
  ok(not fs.exists(p .. ".tsr-tmp") and not fs.exists(p .. ".tsr-new") and not fs.exists(p .. ".tsr-old"))
  ok(vfs.writeFile("/tmp-vfs/bin", "\0\1\2\255", true))
  eq(vfs.readFile("/tmp-vfs/bin", true), "\0\1\2\255")
  cleanup("/tmp-vfs")
end)

test("recover: partial tmp is discarded", function()
  local p = "/tmp-vfs2/a.txt"
  vfs.writeFile(p, "good")
  local h = fs.open(p .. ".tsr-tmp", "w") h.write("par") h.close()
  eq(vfs.recover("/tmp-vfs2"), 1)
  eq(vfs.readFile(p), "good")
  ok(not fs.exists(p .. ".tsr-tmp"))
  cleanup("/tmp-vfs2")
end)

test("recover: complete .new replaces target (crash before swap)", function()
  local p = "/tmp-vfs3/a.txt"
  vfs.writeFile(p, "old")
  local h = fs.open(p .. ".tsr-new", "w") h.write("new") h.close()
  vfs.recover("/tmp-vfs3")
  eq(vfs.readFile(p), "new")
  ok(not fs.exists(p .. ".tsr-new") and not fs.exists(p .. ".tsr-old"))
  cleanup("/tmp-vfs3")
end)

test("recover: .old restored when target missing (crash mid-swap)", function()
  local p = "/tmp-vfs4/a.txt"
  fs.makeDir("/tmp-vfs4")
  local h = fs.open(p .. ".tsr-old", "w") h.write("saved") h.close()
  vfs.recover("/tmp-vfs4")
  eq(vfs.readFile(p), "saved")
  cleanup("/tmp-vfs4")
end)

test("table and JSON helpers", function()
  local t = { a = 1, b = { "x", "y" } }
  vfs.writeTable("/tmp-vfs5/t.tbl", t)
  eq(vfs.readTable("/tmp-vfs5/t.tbl"), t)
  vfs.writeJSON("/tmp-vfs5/t.json", t)
  eq(vfs.readJSON("/tmp-vfs5/t.json"), t)
  eq(vfs.readTable("/tmp-vfs5/missing"), nil)
  cleanup("/tmp-vfs5")
end)

test("ramfs: files, directories, listing, capacity", function()
  local r = vfs.ramfs(10)
  local h = r.open("/a.txt", "w")
  h.write("hello")
  h.close()
  ok(r.exists("/a.txt"))
  eq(r.size("/a.txt"), 5)
  r.makeDir("/d")
  local h2 = r.open("/d/b.txt", "w") h2.write("12") h2.close()
  local names = r.list("/")
  table.sort(names)
  eq(names, { "a.txt", "d" })
  eq(r.getFreeSpace(), 3)
  local h3 = r.open("/big", "w")
  h3.write("way too big for ten bytes")
  throws(function() h3.close() end, "space")
  local rd = r.open("/a.txt", "r")
  eq(rd.readLine(), "hello")
  rd.close()
  local ap = r.open("/a.txt", "a") ap.write("!") ap.close()
  local rd2 = r.open("/a.txt", "r")
  eq(rd2.readAll(), "hello!")
  rd2.close()
  r.delete("/d")
  ok(not r.exists("/d/b.txt"))
  eq(r.getFreeSpace(), 4)
end)

test("mounts route the patched fs API and show up in listings", function()
  vfs.mount("/tsrtest/ram", vfs.ramfs(1024))
  vfs.install()
  ok(fs.exists("/tsrtest/ram"))
  ok(fs.isDir("/tsrtest/ram"))
  ok(fs.isDir("/tsrtest"))
  local h = fs.open("/tsrtest/ram/hello.txt", "w")
  h.writeLine("hi")
  h.write("there")
  h.close()
  ok(fs.exists("/tsrtest/ram/hello.txt"))
  eq(fs.getSize("/tsrtest/ram/hello.txt"), 8)
  local r = fs.open("/tsrtest/ram/hello.txt", "r")
  eq(r.readLine(), "hi")
  eq(r.readAll(), "there")
  r.close()
  eq(fs.list("/tsrtest/ram"), { "hello.txt" })
  local top = fs.list("/")
  local found = false
  for _, n in ipairs(top) do if n == "tsrtest" then found = true end end
  ok(found, "mount parent should appear in root listing")
  -- real fs still works
  fs.makeDir("/tmp-vfs6")
  ok(fs.exists("/tmp-vfs6"))
  fs.delete("/tmp-vfs6")
  -- cross-provider copy and move
  fs.copy("/tsrtest/ram/hello.txt", "/tmp-vfs7.txt")
  eq(vfs.readFile("/tmp-vfs7.txt"), "hi\nthere")
  fs.move("/tmp-vfs7.txt", "/tsrtest/ram/moved.txt")
  ok(not fs.exists("/tmp-vfs7.txt"))
  eq(vfs.readFile("/tsrtest/ram/moved.txt"), "hi\nthere")
  fs.delete("/tsrtest/ram/hello.txt")
  ok(not fs.exists("/tsrtest/ram/hello.txt"))
  vfs.unmount("/tsrtest/ram")
  vfs.uninstall()
  ok(not fs.exists("/tsrtest/ram"))
end)

test("install/uninstall are idempotent and restore the original functions", function()
  local orig = fs.open
  vfs.install()
  vfs.install()
  ok(fs.open ~= orig)
  vfs.uninstall()
  vfs.uninstall()
  ok(fs.open == orig)
end)
