local auth = require("tsr.auth")
local login = require("tsr.login")
local cli = require("tsr.authcli")

local DIR = "/tmp-auth"

local function slurp(path)
  local h = fs.open(path, "r")
  local text = h.readAll()
  h.close()
  return text
end

local function setup()
  auth.guard.uninstall()
  auth.reset()
  if fs.exists(DIR) then fs.delete(DIR) end
  auth.dbPath = DIR .. "/users.db"
  auth.iterations = 3
end

--- A scripted io: `inputs` are consumed in order by ask/secret; everything said is collected.
local function scripted(inputs)
  local io = { said = {}, errs = {}, n = 0, slept = 0 }
  local function nextInput() io.n = io.n + 1 return inputs[io.n] end
  function io.clear() end
  function io.say(t) io.said[#io.said + 1] = t end
  function io.err(t) io.errs[#io.errs + 1] = t end
  function io.ask() return nextInput() end
  function io.secret() return nextInput() end
  function io.sleep(s) io.slept = io.slept + s end
  function io.snapshot() return function() io.restored = true end end
  return io
end

test("users are created, verified and listed", function()
  setup()
  eq(auth.hasUsers(), false)
  ok(auth.addUser("alice", "secret1", { role = "admin" }))
  ok(auth.addUser("bob", "hunter22"))
  eq(auth.hasUsers(), true)
  local u = auth.verify("alice", "secret1")
  eq(u.name, "alice")
  eq(u.role, "admin")
  eq(u.home, "/home/alice")
  local bad, why = auth.verify("alice", "wrong")
  ok(bad == nil and why == "bad")
  bad, why = auth.verify("nobody", "whatever")
  ok(bad == nil and why == "bad")
  eq({ auth.list()[1].name, auth.list()[2].name }, { "alice", "bob" })
  -- the password is never stored or exposed
  local file = slurp(auth.dbPath)
  ok(not file:find("secret1", 1, true))
  ok(auth.get("alice").hash == nil)
end)

test("user names and passwords are validated", function()
  setup()
  ok(not auth.addUser("Bad", "secret1"))
  ok(not auth.addUser("1x", "secret1"))
  ok(not auth.addUser("root", "secret1"))
  ok(not auth.addUser("averyveryverylongname", "secret1"))
  local r, err = auth.addUser("ok", "abc")
  ok(r == nil and err:find("at least"))
  ok(not auth.addUser("ok", "secret1", { role = "wizard" }))
  ok(auth.addUser("ok", "secret1"))
  r, err = auth.addUser("ok", "secret1")
  ok(r == nil and err:find("exists"))
end)

test("the same password hashes differently for different users", function()
  setup()
  auth.addUser("a1", "samepass")
  auth.addUser("a2", "samepass")
  auth.reset()
  local db = slurp(auth.dbPath)
  local t = textutils.unserialize(db)
  ok(t.users.a1.hash ~= t.users.a2.hash)
  ok(t.users.a1.salt ~= t.users.a2.salt)
end)

test("passwords, roles and locking can be changed; the last admin is protected", function()
  setup()
  auth.addUser("root1", "secret1", { role = "admin" })
  auth.addUser("bob", "hunter22")
  ok(auth.setPassword("bob", "newpass1"))
  ok(not auth.verify("bob", "hunter22"))
  ok(auth.verify("bob", "newpass1"))
  ok(auth.setLocked("bob", true))
  local r, why = auth.verify("bob", "newpass1")
  ok(r == nil and why == "locked")
  auth.setLocked("bob", false)
  ok(auth.verify("bob", "newpass1"))
  local bad, err = auth.removeUser("root1")
  ok(bad == nil and err:find("last administrator"))
  bad, err = auth.setRole("root1", "user")
  ok(bad == nil and err:find("last administrator"))
  ok(auth.setRole("bob", "admin"))
  ok(auth.removeUser("root1"))
  ok(not auth.exists("root1"))
  -- survives a restart
  auth.reset()
  ok(auth.verify("bob", "newpass1"))
end)

test("failed attempts are counted", function()
  setup()
  auth.addUser("bob", "hunter22")
  local _, _, n1 = auth.verify("bob", "x")
  local _, _, n2 = auth.verify("bob", "y")
  eq({ n1, n2 }, { 1, 2 })
  ok(auth.verify("bob", "hunter22"))
  local _, _, n3 = auth.verify("bob", "z")
  eq(n3, 1)
end)

test("roles grant actions", function()
  setup()
  auth.addUser("adm", "secret1", { role = "admin" })
  auth.addUser("usr", "secret1")
  auth.addUser("gst", "secret1", { role = "guest" })
  ok(auth.can("adm", "pkg.install"))
  ok(auth.can("usr", "app.run"))
  ok(not auth.can("usr", "pkg.install"))
  ok(not auth.can("gst", "net.use"))
  ok(auth.can(nil, "anything"), "the system may do everything")
  ok(not auth.can("ghost", "app.run"))
  auth.ROLES.ops = { ["svc.*"] = true }
  auth.addUser("ops1", "secret1", { role = "ops" })
  ok(auth.can("ops1", "svc.restart"))
  ok(auth.can("ops1", "svc.x.y"))
  ok(not auth.can("ops1", "pkg.install"))
  auth.ROLES.ops = nil
end)

test("path rules", function()
  setup()
  auth.addUser("adm", "secret1", { role = "admin" })
  auth.addUser("usr", "secret1")
  auth.addUser("oth", "secret1")
  auth.addUser("gst", "secret1", { role = "guest" })
  local P = auth.pathAllowed
  ok(P("adm", "/etc/tsr/system.cfg", "w"))
  ok(P("usr", "/etc/tsr/system.cfg", "r"))
  ok(not P("usr", "/etc/tsr/system.cfg", "w"))
  ok(not P("usr", "/sys/boot.lua", "w"))
  ok(P("usr", "/tmp/x", "w"))
  ok(P("usr", "/home/usr/notes", "w"))
  ok(not P("usr", "/home/oth/notes", "r"), "other homes are private")
  ok(P("adm", "/home/oth/notes", "r"))
  ok(not P("usr", auth.dbPath, "r"))
  ok(not P("usr", "/etc/tsr/net/peers.db", "r"), "pairing keys are secret")
  ok(not P("usr", "/etc/tsr/webgw.cfg", "r"))
  ok(P("adm", "/etc/tsr/net/peers.db", "r"))
  ok(P("usr", "/etc/tsr/network.cfg", "r"), "similar names are not caught")
  ok(not P("gst", "/home/gst/x", "w"))
  ok(P("gst", "/tmp/x", "w"))
  ok(P(nil, "/sys/boot.lua", "w"))
  ok(P(auth.ROOT, "/sys/boot.lua", "w"))
end)

test("the file guard restricts a logged-in process only", function()
  setup()
  auth.addUser("adm", "secret1", { role = "admin" })
  auth.addUser("usr", "secret1")
  fs.makeDir(DIR .. "/sandbox")
  auth.guard.install()
  local okRun, err = pcall(function()
    -- system: allowed anywhere
    local h = fs.open("/tmp-auth-system.txt", "w")
    ok(h)
    h.close()
    fs.delete("/tmp-auth-system.txt")

    auth.setSessionUser("usr")
    local good, e = pcall(fs.open, "/etc/tsr/forbidden.txt", "w")
    ok(not good and tostring(e):find("Access denied"), tostring(e))
    good, e = pcall(fs.delete, "/sys/boot.lua")
    ok(not good and tostring(e):find("Access denied"))
    good, e = pcall(fs.open, "/home/adm/secret", "r")
    ok(not good)
    -- allowed: own home, /tmp, reading the system
    local w = fs.open("/home/usr/note.txt", "w")
    ok(w)
    w.write("hi")
    w.close()
    local r = fs.open("/home/usr/note.txt", "r")
    eq(r.readAll(), "hi")
    r.close()
    local boot = fs.open("/sys/boot.lua", "r")
    ok(boot)
    boot.close()
    fs.delete("/home/usr/note.txt")
    good, e = pcall(fs.move, "/home/usr", "/sys/stolen")
    ok(not good)

    -- elevated sections behave like the system
    auth.asUser(auth.ROOT, function()
      local f = fs.open("/tmp-auth-elevated.txt", "w")
      ok(f)
      f.close()
      fs.delete("/tmp-auth-elevated.txt")
    end)
    eq(auth.current(), "usr")

    -- the user database itself is unreadable for users, but auth keeps working
    good = pcall(fs.open, auth.dbPath, "r")
    ok(not good)
    ok(auth.verify("usr", "secret1"))
  end)
  auth.endSession()
  auth.guard.uninstall()
  if not okRun then error(err, 0) end
end)

test("sessions are per process and inherited by children", function()
  setup()
  local K = require("tsr.kernel")
  K.reset()
  K.init({ term = window.create(term.current(), 1, 1, 20, 5, false) })
  auth.addUser("usr", "secret1")
  local seen = {}
  K.spawn({ name = "session", fn = function()
    auth.setSessionUser("usr")
    K.spawn({ name = "child", window = false, fn = function() seen.child = auth.current() end })
    seen.parent = auth.current()
  end })
  K.spawn({ name = "other", window = false, fn = function() seen.other = auth.current() end })
  K.run()
  eq(seen.parent, "usr")
  eq(seen.child, "usr")
  eq(seen.other, nil)
end)

test("login accepts the right credentials and slows down after failures", function()
  setup()
  auth.addUser("usr", "secret1")
  local io = scripted({ "usr", "nope", "usr", "nope2", "usr", "secret1" })
  local user = login.run({ io = io })
  eq(user.name, "usr")
  eq(auth.current(), "usr")
  eq(io.slept, 1 + 2, "wait grows with each failure")
  auth.endSession()
  local io2 = scripted({ "usr", "bad", "usr", "bad" })
  eq(login.run({ io = io2, attempts = 2 }), nil)
  -- a locked account cannot log in
  auth.setLocked("usr", true)
  local io3 = scripted({ "usr", "secret1" })
  eq(login.run({ io = io3, attempts = 1 }), nil)
  ok(table.concat(io3.said, "\n"):find("locked"))
end)

test("the lock screen needs the password and restores the screen", function()
  setup()
  auth.addUser("usr", "secret1")
  auth.setSessionUser("usr")
  local io = scripted({ "wrong", "secret1" })
  ok(login.lock({ io = io }))
  ok(io.restored)
  local io2 = scripted({ "no", "nope" })
  local r, why = login.lock({ io = io2, attempts = 2 })
  ok(not r and why:find("too many"))
  auth.endSession()
  local r2, why2 = login.lock({ io = scripted({}) })
  ok(not r2 and why2:find("nobody"))
end)

test("commands: first user becomes admin; users manage others", function()
  setup()
  local io = scripted({ "firstpw", "firstpw" })
  ok(cli.useradd({ "boss" }, io))
  eq(auth.get("boss").role, "admin")
  -- passwords must match
  local io2 = scripted({ "aaaaaa", "bbbbbb" })
  ok(not cli.useradd({ "kid" }, io2))
  ok(not auth.exists("kid"))
  -- once users exist, only administrators may add more
  auth.addUser("plain", "plainpw")
  auth.setSessionUser("plain")
  local io3 = scripted({ "x1x1x1", "x1x1x1" })
  ok(not cli.useradd({ "sneaky" }, io3))
  ok(io3.errs[1]:find("administrators"))
  auth.setSessionUser("boss")
  local io4 = scripted({ "kidpw1", "kidpw1" })
  ok(cli.useradd({ "kid", "--role", "guest" }, io4))
  eq(auth.get("kid").role, "guest")
  ok(cli.usermod({ "kid", "--lock" }, scripted({})))
  eq(auth.get("kid").locked, true)
  ok(cli.userdel({ "kid" }, scripted({})))
  local out = scripted({})
  cli.users({}, out)
  eq(#out.said, 2)
  local who = scripted({})
  cli.whoami({}, who)
  eq(who.said[1], "boss")
  auth.endSession()
end)

test("passwd: users change their own password with the old one", function()
  setup()
  auth.addUser("usr", "oldpass1")
  auth.setSessionUser("usr")
  ok(not cli.passwd({}, scripted({ "badold", "newpass2", "newpass2" })))
  ok(cli.passwd({}, scripted({ "oldpass1", "newpass2", "newpass2" })))
  ok(auth.verify("usr", "newpass2"))
  ok(not cli.passwd({ "other" }, scripted({})), "non-admins cannot change others")
  auth.endSession()
end)

test("sudo runs unrestricted for admins only; su needs the target's password", function()
  setup()
  auth.addUser("adm", "adminpw1", { role = "admin" })
  auth.addUser("usr", "userpw11")
  local ranAs
  local function run() ranAs = auth.current() return true end
  auth.setSessionUser("usr")
  ok(not cli.sudo({ "echo" }, scripted({ "userpw11" }), run))
  eq(ranAs, nil)
  auth.setSessionUser("adm")
  ok(not cli.sudo({ "echo" }, scripted({ "wrong" }), run))
  ok(cli.sudo({ "echo" }, scripted({ "adminpw1" }), run))
  eq(ranAs, auth.ROOT)
  eq(auth.current(), "adm")
  -- su
  ranAs = nil
  ok(not cli.su({ "usr" }, scripted({ "wrong" }), run))
  ok(cli.su({ "usr" }, scripted({ "userpw11" }), run))
  eq(ranAs, "usr")
  eq(auth.current(), "adm")
  auth.endSession()
end)

