test("eval, printf, expr, history and type", function()
  local sh = newShell()
  local _, out = run(sh, "eval echo from eval")
  eq(out, "from eval\n")
  _, out = run(sh, "printf '%s=%d\\n' a 5")
  eq(out, "a=5\n")
  _, out = run(sh, "expr 6 '*' 7")
  eq(out, "42\n")
  sh:addHistory("one")
  sh:addHistory("two")
  sh:addHistory("two")
  eq(#sh.history, 2)
  _, out = run(sh, "type echo")
  ok(out:find("builtin", 1, true))
  _, out = run(sh, "type upper")
  ok(out:find("/tmp-sh/bin/upper.lua", 1, true))
  eq(({ run(sh, "type nonesuch") })[1], 1)
end)

