test("completion: programs, paths and variables", function()
  local sh = newShell()
  write(ROOT .. "/alpha.txt", "")
  fs.makeDir(ROOT .. "/alps")
  local C = require("tsr.shell.complete")
  local res = C.complete(sh, "upp")
  eq(res, { "er" })
  res = C.complete(sh, "ec")
  ok(#res > 0)
  res = C.complete(sh, "args al")
  table.sort(res)
  ok(#res >= 2)
  res = C.complete(sh, "cd al")
  ok(#res > 0)
  for _, r in ipairs(res) do ok(r:sub(1, 2) == "ps", r) end
  run(sh, "export MYVAR=1")
  res = C.complete(sh, "unset MYV")
  eq(res, { "AR" })
  -- a registered completion function wins
  sh.api.setCompletionFunction("tmp-sh/bin/args.lua", function(_, index, partial) return { "-" .. index } end)
  eq(C.complete(sh, "args "), { "-1" })
end)

test("output captured from programs keeps blank lines and drops trailing blanks", function()
  local cap = capture.new()
  local prev = term.redirect(cap.term)
  print("a")
  print("")
  print("b   ")
  term.write("c")
  term.redirect(prev)
  eq(cap.text(), "a\n\nb\nc")
end)

test("stdin reader formats", function()
  local r = capture.stdin("12 rest\nline2\nline3")
  eq(r.read("n"), 12)
  eq(r.read("l"), " rest")
  eq(r.read("L"), "line2\n")
  eq(r.read(3), "lin")
  eq(r.read("a"), "e3")
  eq(r.read("l"), nil)
end)

test("an interactive loop runs lines, continues unfinished ones and saves history", function()
  local repl = require("tsr.shell.repl")
  local sh = newShell()
  sh.vars.HOME = "/tmp-sh"
  local lines = { "echo one", "if true; then", "echo inside", "fi", "exit 5" }
  local i = 0
  local cap = capture.new()
  local prev = term.redirect(cap.term)
  local code = repl.run(sh, {
    noRc = true,
    read = function() i = i + 1 return lines[i] end,
  })
  term.redirect(prev)
  eq(code, 5)
  local text = cap.text()
  ok(text:find("one", 1, true) and text:find("inside", 1, true), text)
  ok(fs.exists("/tmp-sh/.tsh_history"))
  eq(repl.prompt(sh, 1), "/tmp-sh> ")
end)
