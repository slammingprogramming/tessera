local exec = require("tsr.shell.exec")
local capture = require("tsr.shell.capture")

local ROOT = "/tmp-sh"

local function write(path, text)
  local h = fs.open(path, "w")
  h.write(text)
  h.close()
end

local function read(path)
  local h = fs.open(path, "r")
  local s = h.readAll()
  h.close()
  return s
end

--- A fresh shell working in a scratch directory with a few helper programs.
local function newShell()
  if fs.exists(ROOT) then fs.delete(ROOT) end
  fs.makeDir(ROOT .. "/bin")
  write(ROOT .. "/bin/upper.lua", [[
    local text = io.read("*a") or ""
    io.write(text:upper())
  ]])
  write(ROOT .. "/bin/args.lua", [[
    print(select("#", ...) .. ":" .. table.concat({ ... }, ","))
  ]])
  write(ROOT .. "/bin/fail.lua", [[ return false ]])
  write(ROOT .. "/bin/code3.lua", [[ return 3 ]])
  write(ROOT .. "/bin/crash.lua", [[ error("boom", 0) ]])
  write(ROOT .. "/bin/lines.lua", [[
    for line in io.lines() do print("[" .. line .. "]") end
  ]])
  write(ROOT .. "/bin/reader.lua", [[
    local a = read()
    local b = read()
    print((a or "nil") .. "|" .. (b or "nil"))
  ]])
  write(ROOT .. "/bin/whoami.lua", [[ print(shell.getenv("WHO") or "none") ]])
  write(ROOT .. "/bin/dirprog.lua", [[ print(shell.dir() .. "|" .. shell.resolve("x")) ]])
  write(ROOT .. "/bin/runner.lua", [[ shell.run("args", "from", "run") ]])
  local sh = exec.new({ dir = "tmp-sh" })
  sh.pathString = "/tmp-sh/bin:/rom/programs"
  return sh
end

--- Run a line and return status plus everything it printed.
local function run(sh, line)
  local cap = capture.new()
  local prev = term.redirect(cap.term)
  local ok, st = pcall(sh.runLine, sh, line)
  term.redirect(prev)
  if not ok then error(st, 0) end
  return st, cap.text()
end

test("echo and builtin status", function()
  local sh = newShell()
  local st, out = run(sh, "echo hello world")
  eq(st, 0)
  eq(out, "hello world\n")
  eq(({ run(sh, "false") })[1], 1)
  eq(({ run(sh, "true") })[1], 0)
end)

test("programs run with arguments; status from return values", function()
  local sh = newShell()
  local st, out = run(sh, "args a 'b c' d")
  eq(out, "3:a,b c,d\n")
  eq(st, 0)
  eq(({ run(sh, "fail") })[1], 1)
  eq(({ run(sh, "code3") })[1], 3)
  local st2, out2 = run(sh, "crash")
  eq(st2, 1)
  eq(({ run(sh, "nosuchthing") })[1], 127)
end)

test("variables, assignment and $?", function()
  local sh = newShell()
  run(sh, "X=hello")
  local _, out = run(sh, 'echo "$X there"')
  eq(out, "hello there\n")
  run(sh, "false")
  _, out = run(sh, "echo $?")
  eq(out, "1\n")
  -- a prefix assignment lasts for one command only
  _, out = run(sh, "WHO=me whoami")
  eq(out, "me\n")
  _, out = run(sh, "whoami")
  eq(out, "none\n")
  run(sh, "export WHO=you")
  _, out = run(sh, "whoami")
  eq(out, "you\n")
  run(sh, "unset WHO")
  _, out = run(sh, "whoami")
  eq(out, "none\n")
end)

test("pipes feed the next program's input", function()
  local sh = newShell()
  local _, out = run(sh, "echo shout | upper")
  eq(out, "SHOUT\n")
  _, out = run(sh, "echo a | echo b | upper")
  eq(out, "B\n")
  write(ROOT .. "/data", "x\ny\nz\n")
  _, out = run(sh, "upper < data | lines")
  eq(out, "[X]\n[Y]\n[Z]\n")
end)

test("read() inside a program takes piped lines", function()
  local sh = newShell()
  local _, out = run(sh, "echo first | reader")
  eq(out, "first|nil\n")
  write(ROOT .. "/two", "one\ntwo\n")
  _, out = run(sh, "reader < two")
  eq(out, "one|two\n")
end)

test("redirects write and append files", function()
  local sh = newShell()
  run(sh, "echo one > out.txt")
  eq(read(ROOT .. "/out.txt"), "one\n")
  run(sh, "echo two >> out.txt")
  eq(read(ROOT .. "/out.txt"), "one\ntwo\n")
  run(sh, "echo three > out.txt")
  eq(read(ROOT .. "/out.txt"), "three\n")
  local st, out = run(sh, "echo gone > out.txt")
  eq(out, "")
  local st2, out2 = run(sh, "echo x < missing.txt")
  eq(st2, 1)
  run(sh, "> empty.txt")
  ok(fs.exists(ROOT .. "/empty.txt"))
end)

test("&& || and ; combine commands", function()
  local sh = newShell()
  local _, out = run(sh, "true && echo yes || echo no")
  eq(out, "yes\n")
  _, out = run(sh, "false && echo yes || echo no")
  eq(out, "no\n")
  _, out = run(sh, "echo a; echo b\necho c")
  eq(out, "a\nb\nc\n")
end)

test("if / elif / else", function()
  local sh = newShell()
  local script = [[
    if false; then echo one
    elif true; then echo two
    else echo three
    fi
  ]]
  local _, out = run(sh, script)
  eq(out, "two\n")
  _, out = run(sh, "if false; then echo a; fi; echo after")
  eq(out, "after\n")
end)

test("for and while loops with break and continue", function()
  local sh = newShell()
  local _, out = run(sh, "for x in a b c; do echo $x; done")
  eq(out, "a\nb\nc\n")
  _, out = run(sh, "for x in 1 2 3 4; do if test $x -eq 2; then continue; fi; if test $x -eq 4; then break; fi; echo $x; done")
  eq(out, "1\n3\n")
  _, out = run(sh, "N=0; while test $N -lt 3; do echo n$N; N=$((N + 1)); done")
  eq(out, "n0\nn1\nn2\n")
  _, out = run(sh, "N=0; until test $N -ge 2; do echo u$N; N=$((N + 1)); done")
  eq(out, "u0\nu1\n")
  -- nested break levels
  _, out = run(sh, "for a in 1 2; do for b in x y; do echo $a$b; break 2; done; done; echo end")
  eq(out, "1x\nend\n")
end)

test("loops can be piped and read stdin", function()
  local sh = newShell()
  local _, out = run(sh, "echo a | while read L; do echo got-$L; done")
  eq(out, "got-a\n")
  _, out = run(sh, "echo x y z | read A B; echo $A/$B")
  eq(out, "x/y z\n")
end)

test("command substitution", function()
  local sh = newShell()
  local _, out = run(sh, 'echo "[$(echo inner)]"')
  eq(out, "[inner]\n")
  run(sh, "V=$(echo captured)")
  _, out = run(sh, "echo $V")
  eq(out, "captured\n")
  _, out = run(sh, "echo $(echo $(echo deep))")
  eq(out, "deep\n")
end)

test("globs expand against the working directory", function()
  local sh = newShell()
  write(ROOT .. "/g1.txt", "")
  write(ROOT .. "/g2.txt", "")
  write(ROOT .. "/other.lua", "")
  local _, out = run(sh, "args g*.txt")
  eq(out, "2:g1.txt,g2.txt\n")
  _, out = run(sh, "args nomatch*")
  eq(out, "1:nomatch*\n")
  _, out = run(sh, "args '*.txt'")
  eq(out, "1:*.txt\n")
end)

test("cd, pwd and relative paths for programs", function()
  local sh = newShell()
  fs.makeDir(ROOT .. "/sub")
  run(sh, "cd sub")
  local _, out = run(sh, "pwd")
  eq(out, "/tmp-sh/sub\n")
  _, out = run(sh, "dirprog")
  eq(out, "tmp-sh/sub|tmp-sh/sub/x\n")
  run(sh, "cd ..")
  _, out = run(sh, "pwd")
  eq(out, "/tmp-sh\n")
  local st = run(sh, "cd nowhere")
  eq(st, 1)
  run(sh, "cd /")
  _, out = run(sh, "pwd")
  eq(out, "/\n")
end)

test("aliases", function()
  local sh = newShell()
  run(sh, "alias hi='echo hello'")
  local _, out = run(sh, "hi there")
  eq(out, "hello there\n")
  run(sh, "unalias hi")
  eq(({ run(sh, "hi") })[1], 127)
  run(sh, "alias say echo")
  _, out = run(sh, "say ok")
  eq(out, "ok\n")
end)

test("test and [ builtins", function()
  local sh = newShell()
  write(ROOT .. "/f", "data")
  local function st(cmd) return (run(sh, cmd)) end
  eq(st("test -f f"), 0)
  eq(st("test -d f"), 1)
  eq(st("test -d ."), 0)
  eq(st("[ -e nothing ]"), 1)
  eq(st("[ a = a ]"), 0)
  eq(st("[ a != a ]"), 1)
  eq(st("[ 3 -lt 10 ]"), 0)
  eq(st("[ ! 3 -gt 10 ]"), 0)
  eq(st("[ -z '' ]"), 0)
  eq(st("[ -n '' ]"), 1)
  eq(st("[ 1 -eq 1 -a 2 -eq 2 ]"), 0)
  eq(st("[ 1 -eq 2 -o 2 -eq 2 ]"), 0)
  eq(st("[ a = a"), 2)
end)

test("scripts get positional parameters, exit and return", function()
  local sh = newShell()
  write(ROOT .. "/s.tsh", [[
    echo "n=$# first=$1 all=$@"
    shift
    echo "after shift: $1"
    if test "$1" = stop; then exit 7; fi
    echo not-reached
  ]])
  local st, out = run(sh, "./s.tsh a stop")
  eq(out:find("n=2 first=a all=a stop", 1, true) ~= nil, true, out)
  ok(out:find("after shift: stop", 1, true))
  ok(not out:find("not-reached", 1, true))
  eq(st, 7)
end)

