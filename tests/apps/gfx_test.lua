local function win(w, h) return window.create(term.current(), 1, 1, w or 20, h or 8, false) end

test("pixels, bounds and clearing", function()
  local c = gfx.new(4, 2)
  eq({ c.w, c.h }, { 8, 6 })
  c:set(0, 0, colors.red)
  c:set(7, 5, colors.blue)
  eq(c:get(0, 0), colors.red)
  eq(c:get(7, 5), colors.blue)
  c:set(-1, 0, colors.red)
  c:set(8, 0, colors.red)
  c:set(0, 6, colors.red)
  eq(c:get(8, 0), nil)
  c:set(3.7, 2.2, colors.lime)
  eq(c:get(3, 2), colors.lime, "coordinates are floored")
  c:clear(colors.gray)
  eq(c:get(5, 4), colors.gray)
  c:clear(nil)
  eq(c:get(5, 4), nil)
end)

test("lines, rectangles and circles", function()
  local c = gfx.new(10, 4)
  c:line(0, 0, 9, 0, colors.white)
  for x = 0, 9 do eq(c:get(x, 0), colors.white) end
  c:line(0, 0, 0, 5, colors.red)
  eq(c:get(0, 5), colors.red)
  c:clear()
  c:line(0, 0, 5, 5, colors.lime)           -- diagonal
  for i = 0, 5 do eq(c:get(i, i), colors.lime) end
  c:clear()
  c:rect(2, 1, 4, 3, colors.blue)
  eq(c:get(2, 1), colors.blue)
  eq(c:get(5, 3), colors.blue)
  eq(c:get(3, 2), nil, "hollow")
  c:rect(10, 0, 3, 3, colors.red, true)
  eq(c:get(10, 1), colors.red)
  c:clear()
  c:circle(10, 6, 4, colors.yellow, true)
  eq(c:get(10, 6), colors.yellow)
  eq(c:get(10, 2), colors.yellow)
  eq(c:get(0, 0), nil)
  c:clear()
  c:circle(10, 6, 4, colors.yellow)
  eq(c:get(10, 6), nil, "an outline leaves the middle empty")
  eq(c:get(14, 6), colors.yellow)
  c:rect(0, 0, 0, 5, colors.red, true)          -- empty rectangles do nothing
end)

test("a cell with two colours becomes a teletext character", function()
  local c = gfx.new(1, 1)
  c:clear(colors.black)
  c:set(0, 0, colors.white)                      -- top-left pixel only
  local text, fg, bg = c:rowBlit(1)
  eq(text:byte(1), 128 + 1)
  eq(fg, colors.toBlit(colors.white))
  eq(bg, colors.toBlit(colors.black))
  c:clear(colors.black)
  c:set(1, 0, colors.red)                        -- top-right pixel
  eq(c:rowBlit(1):byte(1), 128 + 2)
  c:clear(colors.black)
  c:set(0, 1, colors.red)
  eq(c:rowBlit(1):byte(1), 128 + 4, "middle left")
  c:clear(colors.black)
  c:set(1, 1, colors.red)
  eq(c:rowBlit(1):byte(1), 128 + 8, "middle right")
  c:clear(colors.black)
  c:set(0, 2, colors.red)
  eq(c:rowBlit(1):byte(1), 128 + 16, "bottom left")
  -- the bottom-right pixel is the background colour
  c:clear(colors.black)
  c:set(1, 2, colors.green)
  local t2, f2, b2 = c:rowBlit(1)
  eq(t2:byte(1), 159, "the other five pixels are drawn in the foreground colour")
  eq(f2, colors.toBlit(colors.black))
  eq(b2, colors.toBlit(colors.green))
  -- a solid cell is a space-like character in one colour
  c:clear(colors.blue)
  local t3, f3, b3 = c:rowBlit(1)
  eq(t3:byte(1), 128)
  eq(b3, colors.toBlit(colors.blue))
  -- transparent pixels draw as the background argument
  c:clear(nil)
  local _, _, b4 = c:rowBlit(1, colors.gray)
  eq(b4, colors.toBlit(colors.gray))
end)

test("the most common foreground wins when a cell has three colours", function()
  local c = gfx.new(1, 1)
  c:clear(colors.black)
  c:set(0, 0, colors.red)
  c:set(1, 0, colors.red)
  c:set(0, 1, colors.blue)
  local text, fg = c:rowBlit(1)
  eq(fg, colors.toBlit(colors.red))
  eq(text:byte(1), 128 + 1 + 2)
end)

test("flush draws a canvas on a terminal", function()
  local c = gfx.new(3, 2)
  c:clear(colors.black)
  c:rect(0, 0, 6, 6, colors.red, true)
  local w = win(10, 4)
  c:flush(w, 2, 2)
  local text, fg, bg = w.getLine(2)
  eq(text:sub(2, 4), string.rep("\128", 3))
  eq(bg:sub(2, 4), string.rep(colors.toBlit(colors.red), 3))
  eq(w.getLine(1):gsub(" ", ""), "")
  local text3 = w.getLine(3)
  eq(text3:sub(2, 4), string.rep("\128", 3))
end)

test("the font has the characters people need", function()
  for ch in ("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:;!?-+=/\\()_*'\"%<>#[]"):gmatch(".") do ok(font.has(ch), "glyph " .. ch) end
  ok(font.has("a"), "lower case uses capitals")
  ok(not font.has("é"))
  local g = font.glyph("I")
  eq({ g[1][1], g[1][2], g[1][3] }, { true, true, true })
  eq({ g[3][1], g[3][2], g[3][3] }, { false, true, false })
  local unknown = font.glyph("é")
  eq(unknown[1][1], true, "unknown characters are a box")
  eq(unknown[3][2], false)
end)

test("text is drawn at any scale", function()
  local c = gfx.new(10, 4)
  c:text(0, 0, "I", colors.white)
  eq({ c:get(0, 0), c:get(1, 0), c:get(2, 0) }, { colors.white, colors.white, colors.white })
  eq({ c:get(0, 2), c:get(1, 2), c:get(2, 2) }, { nil, colors.white, nil })
  c:clear()
  c:text(0, 0, "I", colors.red, 2)
  eq(c:get(3, 5), colors.red, "scale 2 doubles the pixels")
  eq(c:get(0, 4), nil)
  eq(gfx.textWidth("AB", 1), 7)
  eq(gfx.textWidth("AB", 2), 14)
  eq(gfx.textWidth("", 3), 0)
  eq(gfx.textHeight(2), 10)
  local w = win(20, 4)
  local cols, rows = gfx.bigText(w, 1, 1, "HI", colors.white, colors.black, 1)
  eq({ cols, rows }, { 4, 2 })
  ok(w.getLine(1):byte(1) >= 128, "teletext characters were written")
end)

test("NFP images parse, draw and encode", function()
  local img = image.parse("0f\n f\n")
  eq(img.kind, "nfp")
  eq({ img.width, img.height }, { 2, 2 })
  eq(img.pixels[1][1], colors.white)
  eq(img.pixels[1][2], colors.black)
  eq(img.pixels[2][1], nil, "a space is transparent")
  local c = img:toCanvas()
  eq(c:get(0, 0), colors.white)
  eq(c:get(0, 1), nil)
  eq(image.toNfp(c):sub(1, 2), "0f")
  eq({ img:charSize() }, { 1, 1 })
  local none, err = image.parse("xyz")
  ok(none == nil and err:find("not an NFP"), tostring(err))
  none = image.parse("")
  eq(none, nil)
  -- round trip
  local big = gfx.new(4, 2)
  big:rect(0, 0, 8, 6, colors.blue, true)
  big:set(3, 3, colors.red)
  local again = image.parse(image.toNfp(big)):toCanvas()
  eq(again:get(3, 3), colors.red)
  eq(again:get(0, 0), colors.blue)
end)

test("BIMG images parse, draw, animate and encode", function()
  local f1 = { { "ab", "00", "ff" }, { "cd", "11", "ee" } }
  local f2 = { { "xy", "22", "dd" }, { "zz", "33", "cc" } }
  local text = image.toBimg({ f1, f2 }, { secondsPerFrame = 0.5 })
  local img = image.parse(text)
  eq(img.kind, "bimg")
  eq({ img.width, img.height, #img.frames }, { 2, 2, 2 })
  eq(img.animated, true)
  eq(img.secondsPerFrame, 0.5)
  local w = win(10, 4)
  img:draw(w, 3, 2, 2)
  eq(w.getLine(2):sub(3, 4), "xy")
  eq(w.getLine(3):sub(3, 4), "zz")
  img:draw(w, 1, 1)
  eq(w.getLine(1):sub(1, 2), "ab")
  eq(select(2, w.getLine(1)):sub(1, 2), "00")
  -- a single frame is not an animation
  eq(image.parse(image.toBimg({ f1 })).animated, false)
  -- malformed documents are refused with a reason
  local bad, err = image.parse("{ { { 'ab', '0', 'f' } } }", "bimg")
  ok(bad == nil and err:find("malformed"), tostring(err))
  bad, err = image.parse("{}", "bimg")
  ok(bad == nil and err:find("no frames"), tostring(err))
  bad, err = image.parse("42", "bimg")
  ok(bad == nil)
  -- a canvas exports to BIMG
  local c = gfx.new(2, 1)
  c:clear(colors.blue)
  local doc = c:toBimg()
  eq(#doc[1][1][1], 2)
  local round = image.parse(image.toBimg({ doc[1] }))
  eq({ round.width, round.height }, { 2, 1 })
end)

test("images load from files, detecting the format", function()
  local dir = "/tmp-gfx"
  if fs.exists(dir) then fs.delete(dir) end
  fs.makeDir(dir)
  local function put(name, text)
    local h = fs.open(dir .. "/" .. name, "w")
    h.write(text)
    h.close()
  end
  put("a.nfp", "0f\nf0\n")
  put("b.bimg", image.toBimg({ { { "ab", "00", "ff" } } }))
  put("c.img", "{ { { 'ab', '00', 'ff' } } }")
  put("d.img", "1f1f")
  eq(image.load(dir .. "/a.nfp").kind, "nfp")
  eq(image.load(dir .. "/b.bimg").kind, "bimg")
  eq(image.load(dir .. "/c.img").kind, "bimg", "sniffed by the leading brace")
  eq(image.load(dir .. "/d.img").kind, "nfp")
  local none, err = image.load(dir .. "/missing.nfp")
  ok(none == nil and err:find("cannot open"))
end)

test("palettes apply to a terminal and can be restored", function()
  local set = {}
  local fake = {
    isColor = function() return true end,
    setPaletteColor = function(c, rgb, g, b) set[c] = { rgb, g, b } end,
    nativePaletteColor = function(c) return 0.1, 0.2, 0.3 end,
  }
  ok(palette.apply("nord", fake))
  eq(set[colors.black][1], 0x2E3440)
  eq(set[colors.white][1], 0xECEFF4)
  local count = 0
  for _ in pairs(set) do count = count + 1 end
  eq(count, 16)
  local none, err = palette.apply("neon-pink", fake)
  ok(none == nil and err:find("no such palette"))
  ok(palette.reset(fake))
  eq(set[colors.red], { 0.1, 0.2, 0.3 })
  none, err = palette.apply("nord", { isColor = function() return false end, setPaletteColor = function() end })
  ok(none == nil and err:find("no colour palette"))
  -- every scheme defines all sixteen colours
  for _, name in ipairs(palette.names) do
    for _, cname in ipairs(palette.ORDER) do ok(palette.schemes[name][cname], name .. "." .. cname) end
  end
  local r, g, b = palette.rgb("high-contrast", "white")
  eq({ r, g, b }, { 1, 1, 1 })
end)

local function run(fn, args, env)
  local io = { said = {}, errs = {} }
  function io.say(t) io.said[#io.said + 1] = t end
  function io.err(t) io.errs[#io.errs + 1] = t end
  local r = fn(args, io, env)
  return r, table.concat(io.said, "\n"), table.concat(io.errs, "\n")
end

test("banner draws big text, fits the width, validates options", function()
  local w = win(30, 10)
  local r = run(cli.banner, { "HELLO", "--color", "red" }, { term = w, noShell = true })
  ok(r)
  local text, fg = w.getLine(1)
  ok(text:byte(1) >= 128 or text:byte(2) >= 128)
  ok(fg:find(colors.toBlit(colors.red), 1, true))
  -- scale shrinks to fit a narrow screen
  local narrow = win(12, 10)
  ok(run(cli.banner, { "HELLO", "--scale", "5" }, { term = narrow }))
  local bad, _, err = run(cli.banner, { "x", "--color", "chartreuse" }, { term = w })
  ok(bad == false and err:find("unknown colour"))
  eq(run(cli.banner, {}, { term = w }), false)
  bad, _, err = run(cli.banner, { "x", "--monitor", "nope" }, { term = w, peripheral = { wrap = function() return nil end } })
  ok(bad == false and err:find("no monitor"))
  -- onto a monitor
  local mon = win(20, 6)
  ok(run(cli.banner, { "OK", "--monitor", "mon" }, { term = w, peripheral = { wrap = function() return mon end } }))
  ok(mon.getLine(1):byte(1) >= 128 or mon.getLine(1):byte(2) >= 128)
end)

