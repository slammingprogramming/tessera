test("the palette command saves the choice", function()
  local set = {}
  local fake = win(30, 6)
  fake.setPaletteColor = function(c, v) set[c] = v end
  fake.nativePaletteColor = function() return 0, 0, 0 end
  local config = require("tsr.config")
  config.reset()
  config.paths.system = "/tmp-gfx2/system.cfg"
  local env = { term = fake, config = config }
  local r, text = run(cli.palette, { "list" }, env)
  ok(r and text:find("* default", 1, true) and text:find("gruvbox", 1, true), text)
  ok(run(cli.palette, { "apply", "gruvbox" }, env))
  eq(config.get("ui.palette"), "gruvbox")
  eq(set[colors.black], 0x282828)
  r, text = run(cli.palette, { "list" }, env)
  ok(text:find("* gruvbox", 1, true))
  ok(run(cli.palette, { "show" }, env))
  ok(run(cli.palette, { "reset" }, env))
  eq(config.get("ui.palette"), "default")
  eq(run(cli.palette, { "apply", "nope" }, env), false)
  eq(run(cli.palette, { "bogus" }, env), false)
  -- applySaved
  config.set("ui.palette", "nord", "system")
  set = {}
  ok(palette.applySaved(fake))
  eq(set[colors.black], 0x2E3440)
  config.set("ui.palette", "default", "system")
  eq(palette.applySaved(fake), nil)
end)
