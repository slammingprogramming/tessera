test("snapshots: create, list, and identical content is stored once", function()
  fresh()
  put(DIR .. "/work/a.cfg", "same")
  put(DIR .. "/work/b.cfg", "same")
  put(DIR .. "/work/sub/c.cfg", "other")
  local r = snap.create("first", DIR .. "/work")
  eq({ r.files, r.bytes, r.new }, { 3, 13, 2 })
  local list = snap.list()
  eq({ #list, list[1].name, list[1].files, list[1].root }, { 1, "first", 3, DIR .. "/work" })
  local again, err = snap.create("first", DIR .. "/work")
  ok(again == nil and err:find("already exists"))
  local bad = snap.create("bad name", DIR .. "/work")
  eq(bad, nil)
  local no = snap.create("x", DIR .. "/nonexistent")
  eq(no, nil)
  -- a second snapshot of unchanged files adds no data
  local r2 = snap.create("second", DIR .. "/work")
  eq(r2.new, 0)
end)

test("snapshots: diff against live files and against another snapshot", function()
  fresh()
  put(DIR .. "/work/keep", "k")
  put(DIR .. "/work/edit", "v1")
  put(DIR .. "/work/gone", "g")
  snap.create("s1", DIR .. "/work")
  put(DIR .. "/work/edit", "v2")
  fs.delete(DIR .. "/work/gone")
  put(DIR .. "/work/new", "n")
  local d = snap.diff("s1")
  eq(d, { added = { "new" }, removed = { "gone" }, changed = { "edit" } })
  snap.create("s2", DIR .. "/work")
  eq(snap.diff("s1", "s2"), { added = { "new" }, removed = { "gone" }, changed = { "edit" } })
  eq(snap.diff("s2"), { added = {}, removed = {}, changed = {} })
  local none, err = snap.diff("ghost")
  ok(none == nil and err:find("no such snapshot"))
  none = snap.diff("s1", "ghost")
  eq(none, nil)
end)

test("snapshots: restore puts content back; prune removes extras", function()
  fresh()
  put(DIR .. "/work/a", "alpha")
  put(DIR .. "/work/dir/b", "bravo")
  snap.create("base", DIR .. "/work")
  put(DIR .. "/work/a", "changed")
  fs.delete(DIR .. "/work/dir")
  put(DIR .. "/work/extra", "x")
  local r = snap.restore("base")
  eq(r.restored, 2)
  eq(get(DIR .. "/work/a"), "alpha")
  eq(get(DIR .. "/work/dir/b"), "bravo")
  ok(fs.exists(DIR .. "/work/extra"), "extras stay unless pruned")
  eq(snap.restore("base").restored, 0, "nothing to do the second time")
  r = snap.restore("base", nil, { prune = true })
  eq(r.pruned, 1)
  ok(not fs.exists(DIR .. "/work/extra"))
  -- restore somewhere else, or only some files
  r = snap.restore("base", DIR .. "/copy")
  eq(r.restored, 2)
  eq(get(DIR .. "/copy/a"), "alpha")
  fs.delete(DIR .. "/work/a")
  fs.delete(DIR .. "/work/dir")
  r = snap.restore("base", nil, { only = { "a" } })
  eq(r.restored, 1)
  ok(not fs.exists(DIR .. "/work/dir"))
  local none, err = snap.restore("ghost")
  ok(none == nil and err:find("no such snapshot"))
end)

test("snapshots: a damaged snapshot changes nothing", function()
  fresh()
  put(DIR .. "/work/a", "alpha")
  put(DIR .. "/work/b", "bravo")
  snap.create("base", DIR .. "/work")
  put(DIR .. "/work/a", "edited")
  local m = snap.load("base")
  fs.delete(snap.DIR .. "/blobs/" .. m.files.b.sha)
  local none, err = snap.restore("base")
  ok(none == nil and err:find("damaged"), tostring(err))
  eq(get(DIR .. "/work/a"), "edited", "nothing was touched")
  -- tampered data fails its checksum
  put(snap.DIR .. "/blobs/" .. m.files.b.sha, "tampered")
  none, err = snap.restore("base")
  ok(none == nil and err:find("damaged"), tostring(err))
  eq(get(DIR .. "/work/a"), "edited")
end)

test("snapshots: delete frees data that nothing else uses", function()
  fresh()
  put(DIR .. "/work/shared", "s")
  put(DIR .. "/work/only1", "1")
  snap.create("one", DIR .. "/work")
  fs.delete(DIR .. "/work/only1")
  snap.create("two", DIR .. "/work")
  eq(#fs.list(snap.DIR .. "/blobs"), 2)
  eq(snap.delete("one"), 1)
  eq(#fs.list(snap.DIR .. "/blobs"), 1)
  eq(#snap.list(), 1)
  local none = snap.delete("one")
  eq(none, nil)
end)

test("snapshots: export to another folder and import back", function()
  fresh()
  put(DIR .. "/work/a", "alpha")
  put(DIR .. "/work/b", "bravo")
  snap.create("base", DIR .. "/work")
  eq(snap.export("base", DIR .. "/floppy"), 3)
  ok(fs.exists(DIR .. "/floppy/base.json"))
  eq(snap.export("base", DIR .. "/floppy"), 1, "second export copies only the manifest")
  snap.delete("base")
  eq(#snap.list(), 0)
  eq(snap.import(DIR .. "/floppy", "base"), 2)
  eq(snap.restore("base", DIR .. "/restored").restored, 2)
  eq(get(DIR .. "/restored/b"), "bravo")
  local none, err = snap.import(DIR .. "/floppy", "base")
  ok(none == nil and err:find("already exists"))
  none, err = snap.import(DIR .. "/floppy", "nothing")
  ok(none == nil and err:find("no snapshot"))
  -- corrupted export data is refused
  fs.delete(snap.DIR)
  local blobs = fs.list(DIR .. "/floppy/blobs")
  put(DIR .. "/floppy/blobs/" .. blobs[1], "garbage")
  none, err = snap.import(DIR .. "/floppy", "base")
  ok(none == nil and err:find("damaged"), tostring(err))
end)

test("snap command", function()
  fresh()
  put(DIR .. "/work/a", "alpha")
  local function run(...)
    local io = { said = {}, errs = {} }
    function io.say(t) io.said[#io.said + 1] = t end
    function io.err(t) io.errs[#io.errs + 1] = t end
    local r = snap.run({ ... }, io)
    return r, table.concat(io.said, "\n"), table.concat(io.errs, "\n")
  end
  local r, text = run("list")
  ok(r and text:find("No snapshots", 1, true))
  r, text = run("create", "s1", DIR .. "/work")
  ok(r and text:find("1 files", 1, true), text)
  put(DIR .. "/work/b", "bravo")
  r, text = run("diff", "s1")
  ok(text:find("+ b", 1, true), text)
  r, text = run("diff", "s1", "s1")
  ok(text:find("No differences", 1, true))
  fs.delete(DIR .. "/work/a")
  r, text = run("restore", "s1", "--prune")
  ok(r and text:find("Restored 1 files, removed 1 extra", 1, true), text)
  ok(fs.exists(DIR .. "/work/a") and not fs.exists(DIR .. "/work/b"))
  r, text = run("export", "s1", DIR .. "/out")
  ok(r, text)
  r, text = run("delete", "s1")
  ok(r)
  r, text = run("import", DIR .. "/out", "s1")
  ok(r, text)
  eq(run("create"), false)
  eq(run("restore", "ghost"), false)
  eq(run("bogus"), false)
end)
