test("trash: files and folders go to the bin and come back", function()
  fresh()
  put(DIR .. "/work/a.txt", "alpha")
  put(DIR .. "/work/dir/b.txt", "bravo")
  local id1 = trash.put(DIR .. "/work/a.txt")
  local id2 = trash.put(DIR .. "/work/dir")
  ok(id1 and id2 and id1 ~= id2)
  ok(not fs.exists(DIR .. "/work/a.txt") and not fs.exists(DIR .. "/work/dir"))
  local list = trash.list()
  eq({ #list, list[1].name, list[2].name }, { 2, "a.txt", "dir" })
  eq(list[1].size, 5)
  eq(list[1].path, DIR .. "/work/a.txt")
  eq(trash.totalSize(), 10)
  eq(trash.restore(1), DIR .. "/work/a.txt")
  eq(get(DIR .. "/work/a.txt"), "alpha")
  eq(trash.restore("000002"), DIR .. "/work/dir")
  eq(get(DIR .. "/work/dir/b.txt"), "bravo")
  eq(#trash.list(), 0)
  local none, err = trash.restore(5)
  ok(none == nil and err == "no such entry")
end)

test("trash: restoring never overwrites", function()
  fresh()
  put(DIR .. "/work/a.txt", "old")
  trash.put(DIR .. "/work/a.txt")
  put(DIR .. "/work/a.txt", "new")
  local back = trash.restore(1)
  eq(back, DIR .. "/work/a.txt.restored")
  eq(get(DIR .. "/work/a.txt"), "new")
  eq(get(back), "old")
  -- the original folder may be gone
  put(DIR .. "/work/sub/c.txt", "c")
  trash.put(DIR .. "/work/sub/c.txt")
  fs.delete(DIR .. "/work/sub")
  eq(trash.restore(1), DIR .. "/work/sub/c.txt")
  eq(get(DIR .. "/work/sub/c.txt"), "c")
end)

test("trash: protected paths, missing files, size limit, overflow", function()
  fresh()
  for _, p in ipairs({ "/", "/rom", "/rom/programs", trash.DIR }) do
    local id, err = trash.put(p)
    ok(id == nil and err, p)
  end
  local id, err = trash.put(DIR .. "/work/ghost")
  ok(id == nil and err:find("no such file"))
  trash.MAX_BYTES = 100
  put(DIR .. "/work/big", string.rep("x", 150))
  id, err = trash.put(DIR .. "/work/big")
  ok(id == nil and err:find("too big"))
  ok(fs.exists(DIR .. "/work/big"))
  -- old entries are dropped when the bin is full
  put(DIR .. "/work/f1", string.rep("a", 60))
  put(DIR .. "/work/f2", string.rep("b", 60))
  trash.put(DIR .. "/work/f1")
  trash.put(DIR .. "/work/f2")
  local list = trash.list()
  eq(#list, 1)
  eq(list[1].name, "f2")
end)

test("trash: empty, by age, and discard with and without the bin", function()
  fresh()
  put(DIR .. "/work/x", "1")
  put(DIR .. "/work/y", "2")
  trash.put(DIR .. "/work/x")
  trash.put(DIR .. "/work/y")
  -- age: nothing is older than a day
  eq(trash.empty(1), 0)
  eq(trash.empty(), 2)
  eq(#trash.list(), 0)
  local config = require("tsr.config")
  config.reset()
  put(DIR .. "/work/z", "3")
  ok(trash.discard(DIR .. "/work/z"))
  eq(#trash.list(), 1, "discard uses the bin")
  config.set("trash.enabled", false, "user")
  put(DIR .. "/work/w", "4")
  ok(trash.discard(DIR .. "/work/w"))
  eq(#trash.list(), 1, "disabled: really deleted")
  ok(not fs.exists(DIR .. "/work/w"))
  config.reset()
  eq(({ trash.discard("/rom/programs") })[1], nil)
end)

test("trash command", function()
  fresh()
  put(DIR .. "/work/n.txt", "note")
  local function run(...)
    local io = { said = {}, errs = {} }
    function io.say(t) io.said[#io.said + 1] = t end
    function io.err(t) io.errs[#io.errs + 1] = t end
    local r = trash.run({ ... }, io)
    return r, table.concat(io.said, "\n"), table.concat(io.errs, "\n")
  end
  local r, text = run("list")
  ok(r and text:find("empty", 1, true))
  r, text = run(DIR .. "/work/n.txt")
  ok(r and text:find("Moved", 1, true), text)
  r, text = run("list")
  ok(text:find("n.txt", 1, true) and text:find("note") == nil)
  r, text = run("restore", "1")
  ok(r and get(DIR .. "/work/n.txt") == "note")
  eq(run("restore", "x"), false)
  eq(run("restore", "9"), false)
  local bad, _, err = run(DIR .. "/work/ghost")
  ok(bad == false and err:find("no such file"))
  r, text = run("empty")
  ok(text:find("0 entries", 1, true))
end)

