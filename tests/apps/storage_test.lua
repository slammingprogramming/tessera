local F = dofile("/tests/lib/fakes.lua")
local storage = require("tsrapps.storage")

local function setup(sizes)
  fs.delete("/tmp-st")
  storage.CONFIG = "/tmp-st/storage.cfg"
  local reg = F.inventories(sizes or { input = 27, ores = 27, wood = 27, misc = 27 })
  local api = F.peripheralApi(reg)
  api.hasType = function(name, t) return reg[name] and reg[name]._type == t end
  return { peripheral = api, maxRounds = 1 }, reg
end

test("pattern matching: exact, wildcard, bare suffix and Lua patterns", function()
  local m = storage.matches
  ok(m("minecraft:coal", "minecraft:coal"))
  ok(not m("minecraft:coal", "minecraft:charcoal"))
  ok(m("minecraft:*_ore", "minecraft:iron_ore") and m("minecraft:*_ore", "minecraft:deepslate_gold_ore"))
  ok(not m("minecraft:*_ore", "minecraft:iron_ingot"))
  ok(m("*log", "minecraft:oak_log") and m("*log", "create:log"))
  ok(m("*_planks", "minecraft:oak_planks"))
  ok(m("re:^minecraft:.+_ore$", "minecraft:iron_ore"))
  ok(not m("re:^create:", "minecraft:iron_ore"))
  ok(m("minecraft:iron.ore", "minecraft:iron.ore") and not m("minecraft:iron.ore", "minecraft:ironXore"), "dots are literal")
end)

test("inventories are found on the network", function()
  local env = setup()
  env.peripheral = F.peripheralApi({ a = { _type = "inventory" }, b = { _type = "monitor" }, c = { _type = "inventory" } })
  eq(storage.inventories(env), { "a", "c" })
end)

test("scan totals items across inventories and counts free slots", function()
  local env, reg = setup()
  reg.input.put("minecraft:coal", 100)
  reg.ores.put("minecraft:coal", 20)
  reg.ores.put("minecraft:iron_ore", 5)
  local index = storage.scan(env)
  eq(index.items["minecraft:coal"].total, 120)
  eq(#index.items["minecraft:coal"].at, 3)
  eq(index.free.ores, 25)
  eq(index.free.input, 25)
  eq(#index.invs, 4)
  local hits = storage.find(index, "*_ore")
  eq(#hits, 1)
  eq(hits[1].total, 5)
end)

test("sorting empties the input chest by rules with an overflow chest", function()
  local env, reg = setup()
  local cfg = { input = "input", overflow = "misc", rules = {
    { match = "minecraft:*_ore", to = "ores" }, { match = "*log", to = "wood" } } }
  reg.input.put("minecraft:iron_ore", 70)
  reg.input.put("minecraft:oak_log", 30)
  reg.input.put("minecraft:dirt", 10)
  local r = assert(storage.sortOnce(cfg, env))
  eq(r.moved, 110)
  eq(r.stuck, 0)
  eq(reg.ores.total("minecraft:iron_ore"), 70)
  eq(reg.wood.total("minecraft:oak_log"), 30)
  eq(reg.misc.total("minecraft:dirt"), 10)
  eq(reg.input.total(), 0)
  eq(r.by, { ores = 70, wood = 30, misc = 10 })
end)

test("a full target falls back to the overflow chest; nothing is lost", function()
  local env, reg = setup({ input = 27, ores = 1, misc = 27 })
  local cfg = { input = "input", overflow = "misc", rules = { { match = "*_ore", to = "ores" } } }
  reg.input.put("minecraft:iron_ore", 100)      -- ores holds only 64
  local r = assert(storage.sortOnce(cfg, env))
  eq(reg.ores.total(), 64)
  eq(reg.misc.total(), 36)
  eq(r.stuck, 0)
  eq(reg.input.total(), 0)
end)

test("items with no rule and no overflow stay put and are reported", function()
  local env, reg = setup()
  local cfg = { input = "input", rules = { { match = "*_ore", to = "ores" } } }
  reg.input.put("minecraft:dirt", 12)
  reg.input.put("minecraft:iron_ore", 3)
  local r = assert(storage.sortOnce(cfg, env))
  eq(r.moved, 3)
  eq(r.stuck, 12)
  eq(reg.input.total("minecraft:dirt"), 12)
  local bad, err = storage.sortOnce({ input = "ghost", rules = {} }, env)
  ok(bad == nil and err:find("ghost"))
end)

test("get gathers items from the network into an inventory", function()
  local env, reg = setup()
  reg.ores.put("minecraft:coal", 40)
  reg.misc.put("minecraft:coal", 40)
  local moved = storage.get(env, "minecraft:coal", 60, "input")
  eq(moved, 60)
  eq(reg.input.total("minecraft:coal"), 60)
  eq(reg.ores.total("minecraft:coal") + reg.misc.total("minecraft:coal"), 20)
  eq(storage.get(env, "minecraft:nothing", 5, "input"), 0)
  eq(storage.get(env, "minecraft:coal", 1000, "input"), 20, "gives what exists")
end)

test("commands: scan, find, rules, input, sort, get", function()
  local env, reg = setup()
  reg.input.put("minecraft:iron_ore", 10)
  reg.wood.put("minecraft:oak_log", 5)
  local io = F.io()
  ok(storage.main({ "scan" }, io, env))
  ok(io.said[1]:find("4 inventories, 2 kinds"))
  ok(storage.main({ "find", "*log" }, io, env))
  ok(io.said[#io.said]:find("oak_log: 5") and io.said[#io.said]:find("wood%[1%]x5"))
  ok(storage.main({ "find", "nothing" }, io, env))
  ok(io.said[#io.said] == "Not found.")
  eq(storage.main({ "sort" }, F.io(), env), false, "needs an input chest")
  ok(storage.main({ "input", "input" }, io, env))
  ok(storage.main({ "rule", "add", "*_ore", "ores" }, io, env))
  ok(storage.main({ "rule", "add", "*log", "wood" }, io, env))
  eq(storage.main({ "rule", "add", "*x", "ghost" }, F.io(), env), false)
  ok(storage.main({ "rule", "list" }, io, env))
  ok(storage.main({ "sort", "--once" }, io, env))
  eq(reg.ores.total("minecraft:iron_ore"), 10)
  ok(storage.main({ "rule", "remove", "1" }, io, env))
  eq(#storage.load().rules, 1)
  eq(storage.main({ "rule", "remove", "9" }, F.io(), env), false)
  ok(storage.main({ "get", "*log", "3", "input" }, io, env))
  eq(reg.input.total("minecraft:oak_log"), 3)
  eq(storage.main({ "get", "*log", "x", "input" }, F.io(), env), false)
  eq(storage.main({ "get", "*log", "3", "ghost" }, F.io(), env), false)
  eq(storage.main({ "bogus" }, F.io(), env), false)
  fs.delete("/tmp-st")
end)
