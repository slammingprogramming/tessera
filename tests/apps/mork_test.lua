local F = dofile("/tests/lib/fakes.lua")
local mork = require("tsrapps.mork")

local function play(st, commands)
  local last
  for _, c in ipairs(commands) do last = mork.exec(st, c) end
  return last
end

local function text(lines) return table.concat(lines, "\n") end

test("a new game starts in the cell", function()
  local st = mork.new()
  eq(st.room, "cell")
  local d = mork.describe(st)
  eq(d[1], "Stone Cell")
  ok(text(d):find("bread"))
  ok(not text(d):find("bench here"), "scenery is not listed as loose items")
end)

test("the perfect run: torch, key, bread, vault, diamond, out", function()
  local st = mork.new()
  play(st, { "take bread", "north", "east", "take torch", "take sword", "west", "west", "take key", "east", "north",
             "give bread to zombie", "open door", "east", "take diamond", "west", "north" })
  eq(st.status, "won")
  eq(st.score, 10 + 15 + 10 + 20 + 25 + 10, "torch 10, key 15, zombie(bread) 10, door 20, diamond 25, escape 10")
end)

test("fighting the zombie with the sword scores more than feeding it", function()
  local st = mork.new()
  play(st, { "n", "e", "take sword", "w", "n", "attack zombie with sword", "n" })
  eq(st.status, "won")
  eq(st.score, 20 + 10)
  ok(not st.inv.diamond)
end)

test("escaping without the diamond says so", function()
  local st = mork.new()
  play(st, { "take bread", "n", "n", "give bread to zombie" })
  local out = mork.exec(st, "n")
  eq(st.status, "won")
  ok(text(out):find("treasure is still below"))
end)

test("the zombie blocks the stairs until dealt with", function()
  local st = mork.new()
  local out = play(st, { "n", "n", "n" })
  ok(text(out):find("blocks the stairs"))
  eq(st.status, "playing")
  eq(st.room, "hall")
  out = mork.exec(st, "attack zombie")
  ok(text(out):find("bare hands"))
  out = mork.exec(st, "look")
  ok(text(out):find("zombie shambles"))
end)

test("the iron door needs the key", function()
  local st = mork.new()
  play(st, { "n", "n" })
  ok(text(mork.exec(st, "open door")):find("locked"))
  ok(text(mork.exec(st, "east")):find("locked tight"))
  eq(st.room, "hall")
end)

test("the dark cave: no light, no key; a second careless action is fatal", function()
  local st = mork.new()
  play(st, { "n", "w" })
  ok(text(mork.exec(st, "look")):find("pitch black"))
  ok(text(mork.exec(st, "take key")):find("too dark"))
  local out = mork.exec(st, "take key")
  eq(st.status, "dead")
  ok(text(out):find("creeper") and text(out):find("You have died"))
end)

test("leaving the dark cave resets the warning, and the torch reveals the key", function()
  local st = mork.new()
  play(st, { "n", "w", "take key", "e" })
  eq(st.room, "corridor")
  eq(st.status, "playing")
  play(st, { "e", "take torch", "w", "w" })
  ok(text(mork.describe(st)):find("iron key"))
  ok(text(mork.exec(st, "take key")):find("Taken"))
  ok(st.inv.key)
end)

test("inventory, drop, take all, and unknown commands", function()
  local st = mork.new()
  ok(text(mork.exec(st, "inventory")):find("nothing"))
  play(st, { "take bread" })
  ok(text(mork.exec(st, "i")):find("loaf of bread"))
  ok(text(mork.exec(st, "drop bread")):find("Dropped"))
  ok(text(mork.exec(st, "take all")):find("Taken: loaf of bread"))
  ok(text(mork.exec(st, "dance wildly")):find("don't understand"))
  ok(text(mork.exec(st, "")):find("Say something"))
  ok(text(mork.exec(st, "take bench")):find("can't take"))
  ok(text(mork.exec(st, "take unicorn")):find("no such thing"))
  play(st, { "n", "e" })
  ok(text(mork.exec(st, "take all")):find("torch") and st.inv.sword)
end)

test("examine, read and eat", function()
  local st = mork.new()
  ok(text(mork.exec(st, "examine bench")):find("bowl"))
  ok(text(mork.exec(st, "look at the bench")):find("bowl"))
  play(st, { "take bread" })
  ok(text(mork.exec(st, "eat bread")):find("dry but filling"))
  ok(not st.inv.bread)
  ok(text(mork.exec(st, "eat torch")):find("can't eat"))
  play(st, { "n", "n", "w" })
  ok(text(mork.exec(st, "read book")):find("zombie in the hall"))
end)

test("go with articles and abbreviations, and the wall", function()
  local st = mork.new()
  ok(text(mork.exec(st, "go to the north")):find("Torchless Corridor"))
  eq(st.room, "corridor")
  ok(text(mork.exec(st, "s")):find("Stone Cell"))
  ok(text(mork.exec(st, "west")):find("can't go that way"))
end)

test("score, help, quit", function()
  local st = mork.new()
  ok(text(mork.exec(st, "score")):find("0 of 100"))
  ok(text(mork.exec(st, "help")):find("Commands"))
  ok(text(mork.exec(st, "quit")):find("give up"))
  eq(st.status, "quit")
end)

test("save and load round trip", function()
  fs.delete("/tmp-mork")
  local st = mork.new()
  play(st, { "take bread", "n" })
  ok(mork.save(st, "/tmp-mork/game.sav"))
  local back = mork.load("/tmp-mork/game.sav")
  eq(back.room, "corridor")
  ok(back.inv.bread)
  eq(back.score, st.score)
  eq(mork.load("/tmp-mork/none.sav"), nil)
  fs.delete("/tmp-mork")
end)

test("the game loop plays a script and reports the win", function()
  fs.delete("/tmp-mork")
  local script = { "n", "e", "take torch", "take sword", "w", "w", "take key", "e", "n", "attack zombie with sword",
                   "open door", "e", "take diamond", "w", "save", "n" }
  local io = F.io()
  local i = 0
  local env = { savePath = "/tmp-mork/g.sav", readLine = function() i = i + 1 return script[i] end }
  ok(mork.main({}, io, env))
  ok(io.said[#io.said]:find("Score: 100 of 100"), io.said[#io.said])
  ok(fs.exists("/tmp-mork/g.sav"))
  -- loading resumes mid-game
  local io2 = F.io()
  local script2 = { "load", "score", "quit" }
  local j = 0
  mork.main({}, io2, { savePath = "/tmp-mork/g.sav", readLine = function() j = j + 1 return script2[j] end })
  local joined = table.concat(io2.said, "\n")
  ok(joined:find("Great Hall") or joined:find("Score: 90"), joined)
  fs.delete("/tmp-mork")
end)
