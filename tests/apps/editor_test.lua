test("selection, copy text and delete", function()
  local b = buf("hello world\nsecond line")
  b:setCursor(1, 1)
  b:move(0, 5, true)
  eq(b:selectedText(), "hello")
  b:move(1, 0, true)
  ok(b:selectedText():find("^hello world\n"))
  b:setCursor(1, 7)
  b:select(1, 7)
  b:setCursor(2, 7, true)
  eq(b:selectedText(), "world\nsecond")
  ok(b:deleteSelection())
  eq(b.lines, { "hello  line" })
  eq({ b.cy, b.cx }, { 1, 7 })
  b:selectAll()
  eq(b:selectedText(), "hello  line")
  b:insert("x")
  eq(b.lines, { "x" })
  -- left/right collapse a selection to its edges
  b = buf("abcdef")
  b:setCursor(1, 2)
  b:move(0, 3, true)
  b:move(0, -1)
  eq({ b.cy, b.cx }, { 1, 2 })
  eq(b.anchor, nil)
end)

test("undo and redo restore text and cursor exactly", function()
  local b = buf("alpha\nbeta")
  b:setCursor(1, 6)
  for c in (" one"):gmatch(".") do b:insert(c) end
  eq(b.lines[1], "alpha one")
  b:setCursor(2, 1)
  b:insert("\n")
  eq(b.lines, { "alpha one", "", "beta" })
  ok(b:undo())
  eq(b.lines, { "alpha one", "beta" })
  ok(b:undo())
  eq(b.lines, { "alpha", "beta" }, "typing in a row undoes as one step")
  ok(not b:undo())
  ok(b:redo() and b:redo())
  eq(b.lines, { "alpha one", "", "beta" })
  ok(not b:redo())
  -- a new edit clears the redo stack
  b:undo()
  b:insert("!")
  ok(not b:redo())
  -- deleting a range is undoable
  b:selectAll()
  b:deleteSelection()
  eq(b.lines, { "" })
  b:undo()
  eq(b:text(), "alpha one\n!beta\n")
end)

test("undo of a multi-line deletion and join", function()
  local b = buf("one\ntwo\nthree")
  b:setCursor(1, 3)
  b:select(1, 3)
  b:setCursor(3, 3, true)
  b:deleteSelection()
  eq(b.lines, { "onree" })
  b:undo()
  eq(b.lines, { "one", "two", "three" })
  b:redo()
  eq(b.lines, { "onree" })
end)

test("autoindent keeps and extends the indentation", function()
  local b = buf("")
  b:insert("function f()", true)
  b:insert("\n", true)
  eq(b.lines[2], "  ", "one level after function")
  b:insert("if x then", true)
  b:insert("\n", true)
  eq(b.lines[3], "    ")
  b:insert("y()", true)
  b:insert("\n", true)
  eq(b.lines[4], "    ", "same level as the line above")
  local plain = buf("  text")
  plain:setCursor(1, 7)
  plain:insert("\n", true)
  eq(plain.lines[2], "  ")
  local off = buf("  text")
  off:setCursor(1, 7)
  off:insert("\n", false)
  eq(off.lines[2], "")
end)

test("indent and outdent lines", function()
