test("search finds forwards, backwards and wraps", function()
  local b = buf("foo bar\nbaz foo\nFOO end")
  b:setCursor(1, 1)
  local y, x, len = b:find("foo")
  eq({ y, x, len }, { 1, 1, 3 })
  b:setCursor(1, 2)
  y, x = b:find("foo")
  eq({ y, x }, { 2, 5 })
  b:setCursor(3, 1)
  y, x = b:find("foo")
  eq({ y, x }, { 1, 1 }, "wraps around")
  y, x = b:find("foo", { ignoreCase = true })
  eq({ y, x }, { 3, 1 }, "case-insensitive finds FOO at the cursor")
  b:setCursor(3, 1)
  y, x = b:find("foo", { backwards = true })
  eq({ y, x }, { 2, 5 })
  eq(b:find("zzz"), nil)
  eq(b:find(""), nil)
  -- patterns
  y, x, len = b:find("b%a+", { pattern = true })
  ok(y ~= nil and len == 3)
  -- findNext selects the match
  b:setCursor(1, 1)
  ok(b:findNext("bar"))
  eq(b:selectedText(), "bar")
  ok(not b:findNext("nothing"))
end)

test("replace all", function()
  local b = buf("cat concat\nCat\ncat")
  eq(b:replaceAll("cat", "dog"), 3)
  eq(b.lines, { "dog condog", "Cat", "dog" })
  eq(b:replaceAll("cat", "X", true), 1)
  eq(b.lines[2], "X")
  eq(b:replaceAll("", "x"), 0)
  b:undo()
  eq(b.lines[2], "Cat")
end)

test("Lua highlighting", function()
  local s = lua.highlight({ 'local x = "str" -- note', "if x == 12.5 then print(0xFF) end" })
  eq(s[1], "kkkkk" .. "ooooo" .. "sssss" .. "o" .. "ccccccc")
  eq(#s[1], #'local x = "str" -- note')
  eq(s[2]:sub(1, 2), "kk")
  eq(s[2]:sub(9, 12), "nnnn")
  ok(s[2]:find("fffff", 1, true), "print is a library function: " .. s[2])
  -- multi-line strings and comments carry over
  local m = lua.highlight({ "--[[ start", "still comment", "end ]] x = 1", "s = [==[ long", "string ]==] y" })
  eq(m[1], string.rep("c", 10))
  eq(m[2], string.rep("c", 13))
  eq(m[3]:sub(1, 6), "cccccc")
  eq(m[3]:sub(8, 8), "o")
  ok(m[4]:sub(5):find("^s+$"), m[4])
  eq(m[5]:sub(1, 6), "ssssss")
  -- escapes inside strings
  local e = lua.highlight({ [[x = "a\"b" y]] })
  eq(e[1]:sub(5, 9), "sssss")
  eq(e[1]:sub(11, 11), "o")
end)

--- A scripted editor over a window with an in-memory file system.
local function session(text, path)
  local files = {}
  if path and text then files[path] = text end
  local t = window.create(term.current(), 1, 1, 40, 10, false)
  local ed = edit.new({ path = path, term = t, readFile = function(p) return files[p] end,
                        writeFile = function(p, s) files[p] = s return true end })
  return ed, files, t
end

local function press(ed, ...)
  for _, k in ipairs({ ... }) do
    ed:event("key", k, false)
    ed:event("key_up", k)
  end
end

local function ctrl(ed, k)
  ed:event("key", keys.leftCtrl, false)
  ed:event("key", k, false)
  ed:event("key_up", k)
  ed:event("key_up", keys.leftCtrl)
end

local function type_(ed, s)
  for c in s:gmatch(".") do ed:event("char", c) end
end

test("the editor loads, draws and saves a file", function()
  local ed, files, t = session("line one\nline two\n", "/a.txt")
  ed:draw()
  local first = t.getLine(1)
  ok(first:find("1 line one", 1, true), first)
  ok(t.getLine(10):find("/a.txt", 1, true))
  type_(ed, "X")
  eq(ed.buf.lines[1], "Xline one")
  ok(t.getLine(10) ~= nil)
  ed:draw()
  ok(t.getLine(10):find("*", 1, true), "modified marker")
  ctrl(ed, keys.s)
  eq(files["/a.txt"], "Xline one\nline two\n")
  ok(not ed.buf.modified)
  ok(ed.message:find("Saved", 1, true))
end)

test("keyboard editing: arrows, shift-selection, clipboard, undo", function()
  local ed = session("hello world\nsecond", "/b.txt")
  press(ed, keys.right, keys.right)
  ed:event("key", keys.leftShift, false)
  press(ed, keys.right, keys.right, keys.right)
  ed:event("key_up", keys.leftShift)
  eq(ed.buf:selectedText(), "llo")
  ctrl(ed, keys.c)
  eq(ed.clipboard, "llo")
  press(ed, keys.end_ or keys["end"])
  ctrl(ed, keys.v)
  eq(ed.buf.lines[1], "hello worldllo")
  ctrl(ed, keys.z)
  eq(ed.buf.lines[1], "hello world")
  ctrl(ed, keys.y)
  eq(ed.buf.lines[1], "hello worldllo")
  -- cut a line when nothing is selected
  press(ed, keys.down)
  ctrl(ed, keys.x)
  eq(ed.clipboard, "second\n")
  eq(ed.buf.lines, { "hello worldllo" })
  -- paste event inserts text
  ed:event("paste", "pasted")
  ok(ed.buf.lines[1]:find("pasted", 1, true))
  -- select all and type replaces everything
  ctrl(ed, keys.a)
  type_(ed, "new")
  eq(ed.buf.lines, { "new" })
  -- tab indents, shift+tab outdents
  press(ed, keys.tab)
  eq(ed.buf.lines[1], "new  ")
end)

test("find, replace and go to line through the status bar", function()
  local ed, _, t = session("alpha\nbeta\ngamma\nbeta again", "/c.txt")
  ctrl(ed, keys.f)
  ok(ed.prompt and ed.prompt.label == "Find: ")
  type_(ed, "beta")
  press(ed, keys.enter)
  eq(ed.buf:selectedText(), "beta")
  eq(ed.buf.cy, 2)
  press(ed, keys.f3)
  eq(ed.buf.cy, 4)
  ed:event("key", keys.leftShift, false)
  press(ed, keys.f3)
  ed:event("key_up", keys.leftShift)
  eq(ed.buf.cy, 2)
  press(ed, keys.f3)
  press(ed, keys.f3)
  ed:draw()
  ctrl(ed, keys.f)           -- a fresh find prompt
  type_(ed, "zzz")
  press(ed, keys.enter)
  ok(ed.message:find("Not found", 1, true))
  -- replace all
  ed.lastFind = nil
  ctrl(ed, keys.h)
  type_(ed, "a")
  press(ed, keys.enter)
  type_(ed, "A")
  press(ed, keys.enter)
  ok(ed.message:find("replaced", 1, true), ed.message)
  eq(ed.buf.lines[1], "AlphA")
  -- go to line
  ctrl(ed, keys.l)
  type_(ed, "3")
  press(ed, keys.enter)
  eq(ed.buf.cy, 3)
  -- escape cancels a prompt
  ctrl(ed, keys.l)
  press(ed, 1)
  ok(ed.prompt == nil)
end)

test("quitting asks about unsaved changes", function()
  local ed, files = session("keep\n", "/d.txt")
  ctrl(ed, keys.q)
  ok(ed.done, "clean buffer quits at once")
  ed, files = session("keep\n", "/d.txt")
  type_(ed, "x")
  ctrl(ed, keys.q)
  ok(ed.prompt and not ed.done)
  press(ed, 1)
  ok(not ed.done and ed.prompt == nil)
  ctrl(ed, keys.q)
  type_(ed, "n")
  press(ed, keys.enter)
  ok(ed.done)
  eq(files["/d.txt"], "keep\n", "discarded")
  ed, files = session("keep\n", "/d.txt")
  type_(ed, "x")
  ctrl(ed, keys.q)
  type_(ed, "y")
  press(ed, keys.enter)
  ok(ed.done)
  eq(files["/d.txt"], "xkeep\n")
end)

