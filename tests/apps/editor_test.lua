local Buffer = require("tsr.edit.buffer")
local lua = require("tsr.edit.lua")
local edit = require("tsr.edit.ui")

local function buf(text) return Buffer.new(text) end

test("loading and saving text", function()
  local b = buf("one\ntwo\r\nthree\n")
  eq(b.lines, { "one", "two", "three" })
  eq(b:text(), "one\ntwo\nthree\n")
  eq(buf("").lines, { "" })
  eq(buf("no newline").lines, { "no newline" })
  eq(buf("a\n\n\nb").lines, { "a", "", "", "b" })
  ok(not b.modified)
end)

test("typing, newlines and deleting", function()
  local b = buf("")
  b:insert("hello")
  b:insert("\n")
  b:insert("world")
  eq(b.lines, { "hello", "world" })
  eq({ b.cy, b.cx }, { 2, 6 })
  b:backspace()
  eq(b.lines[2], "worl")
  b:setCursor(2, 1)
  b:backspace()               -- joins with the line above
  eq(b.lines, { "helloworl" })
  eq({ b.cy, b.cx }, { 1, 6 })
  b:deleteForward()
  eq(b.lines[1], "helloorl")
  b:setCursor(1, 9)
  b:deleteForward()           -- at the end of the last line: nothing
  eq(b.lines[1], "helloorl")
  ok(b.modified)
end)

test("the cursor moves across lines and remembers its column", function()
  local b = buf("abcdef\nab\nabcdef")
  b:setCursor(1, 5)
  b:move(1, 0)
  eq({ b.cy, b.cx }, { 2, 3 }, "clamped to the short line")
  b:move(1, 0)
  eq({ b.cy, b.cx }, { 3, 5 }, "and back to the wanted column")
  b:move(0, 1)
  b:move(0, 1)
  b:move(0, 1)
  eq({ b.cy, b.cx }, { 3, 7 })
  b:move(0, 1)
  eq({ b.cy, b.cx }, { 3, 7 }, "stops at the end of the file")
  b:setCursor(2, 1)
  b:move(0, -1)
  eq({ b.cy, b.cx }, { 1, 7 }, "left at the start wraps to the previous line")
  b:move(0, 1)
  eq({ b.cy, b.cx }, { 2, 1 })
  b:home()
  eq(b.cx, 1)
  b:endOfLine()
  eq(b.cx, 3)
  b:gotoLine(99)
  eq(b.cy, 3)
end)

test("smart home", function()
