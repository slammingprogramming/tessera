test("mouse: click, drag-select and scroll", function()
  local lines = {}
  for i = 1, 30 do lines[i] = "line " .. i end
  local ed = session(table.concat(lines, "\n"), "/e.txt")
  ed:draw()
  local gw = ed:gutterWidth()
  ed:event("mouse_click", 1, gw + 3, 2)
  eq({ ed.buf.cy, ed.buf.cx }, { 2, 3 })
  ed:event("mouse_drag", 1, gw + 5, 4)
  eq(ed.buf:selectedText(), "ne 2\nline 3\nline")
  ed:event("mouse_scroll", 1, 5, 5)
  eq(ed.top, 4)
  ed:event("mouse_scroll", -1, 5, 5)
  eq(ed.top, 1)
  ed:event("mouse_scroll", 100, 5, 5)
  eq(ed.top, 30 - 9 + 1)
end)

test("the view scrolls to keep the cursor visible", function()
  local lines = {}
  for i = 1, 40 do lines[i] = string.rep("x", 60) end
  local ed, _, t = session(table.concat(lines, "\n"), "/f.txt")
  ed.buf:setCursor(25, 55)
  ed:draw()
  ok(ed.top > 1 and ed.top <= 25)
  ok(ed.left > 0, "scrolled right: " .. ed.left)
  local cx, cy = t.getCursorPos()
  ok(cx >= 1 and cx <= 40 and cy >= 1 and cy <= 9, cx .. "," .. cy)
end)
