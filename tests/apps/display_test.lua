local F = dofile("/tests/lib/fakes.lua")
local display = require("tsrapps.display")

local function env(mon)
  return { peripheral = F.peripheralApi({ monitor_1 = mon }), ingameHours = function() return 13.5 end,
           utcSeconds = function() return 3600 * 7 + 60 * 5 end, maxFrames = 1, uptimeSeconds = function() return 3720 end }
end

test("formatClock: 12h and 24h, seconds, wrap-around", function()
  eq(display.formatClock(13.5, {}), "01:30 PM")
  eq(display.formatClock(13.5, { h24 = true }), "13:30")
  eq(display.formatClock(0, {}), "12:00 AM")
  eq(display.formatClock(12, {}), "12:00 PM")
  eq(display.formatClock(9.5, { h24 = true, seconds = true }), "09:30:00")
  eq(display.formatClock(23.99999, { h24 = true }), "00:00", "rounds to the nearest second and wraps")
  eq(display.formatClock(6.25, { h24 = true, seconds = true }), "06:15:00")
end)

test("find picks the named or the first monitor", function()
  local mon = F.monitor()
  local e = env(mon)
  local m, name = display.find(nil, e)
  ok(m == mon and name == "monitor_1")
  m = display.find("monitor_1", e)
  ok(m == mon)
  local none, why = display.find("left", e)
  ok(none == nil and why:find("no monitor on left"))
  none, why = display.find(nil, { peripheral = F.peripheralApi({}) })
  ok(none == nil and why:find("no monitor attached"))
end)

test("drawCentered centres text both ways and clips to the width", function()
  local mon = F.monitor(10, 5)
  display.drawCentered(mon, { "hi", "world!!!!!!!!!!" })
  local lines = mon.lines()
  eq(lines[2], "    hi", "centred horizontally")
  eq(lines[3], "world!!!!!", "long lines are clipped")
  eq(lines[1], "")
end)

test("clock frame shows the in-game or real time", function()
  local mon = F.monitor(20, 5)
  local e = env(mon)
  eq(display.clockFrame(mon, { ["24h"] = true }, e), "13:30")
  ok(mon.text():find("13:30", 1, true))
  eq(display.clockFrame(mon, { real = true, ["24h"] = true }, e), "07:05")
  eq(display.clockFrame(mon, {}, e), "01:30 PM")
end)

test("monclock command sets the scale and draws", function()
  local mon = F.monitor(20, 5)
  local io = F.io()
  ok(display.monclock({ "--scale", "3", "--24h" }, io, env(mon)))
  eq(mon.scale, 3)
  ok(mon.text():find("13:30", 1, true))
  local none = F.io()
  eq(display.monclock({}, none, { peripheral = F.peripheralApi({}) }), false)
  ok(none.errs[1]:find("no monitor"))
end)

test("status lines describe the computer and its peripherals", function()
  local e = env(F.monitor())
  e.peripheral = F.peripheralApi({ a = { _type = "speaker" }, b = { _type = "speaker" }, c = { _type = "monitor" } })
  local lines = display.statusLines(e)
  local text = table.concat(lines, "\n")
  ok(text:find("up 1h 02m", 1, true), text)
  ok(text:find("time 13:30", 1, true))
  ok(text:find("speaker x2", 1, true) and text:find("monitor x1", 1, true))
  ok(text:find("disk ", 1, true))
end)

test("monstat draws the board", function()
  local mon = F.monitor(24, 10)
  local e = env(mon)
  ok(display.monstat({}, F.io(), e))
  ok(mon.text():find("monitor x1", 1, true))
  eq(mon.scale, 1)
end)

test("monwrite wraps, colours and clears", function()
  local mon = F.monitor(12, 6)
  local e = env(mon)
  ok(display.monwrite({ "hello", "there", "wonderful", "world" }, F.io(), e))
  local lines = mon.lines()
  local found = 0
  for _, l in ipairs(lines) do if l ~= "" then found = found + 1 end end
  ok(found >= 2, "text wrapped to several lines: " .. mon.text())
  ok(display.monwrite({ "--color", "red", "alert" }, F.io(), e))
  eq(mon.fg, colors.red)
  ok(display.monwrite({}, F.io(), e))
  eq(mon.text(), string.rep("\n", 5))
  eq(display.monwrite({ "--color", "plaid", "x" }, F.io(), e), false)
  eq(display.monwrite({ "--side", "top", "x" }, F.io(), e), false)
end)
