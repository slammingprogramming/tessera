  [">"] = "100010001010100", ["#"] = "101111101111101", ["["] = "110100100100110", ["]"] = "011001001001011",
}

--- Rows of a character: three booleans per row, five rows. Unknown characters are drawn as a hollow box.
function M.glyph(ch)
  local bits = G[ch] or G[ch:upper()] or "111101101101111"
  local rows = {}
  for r = 0, 4 do
    rows[r + 1] = { bits:sub(r * 3 + 1, r * 3 + 1) == "1", bits:sub(r * 3 + 2, r * 3 + 2) == "1", bits:sub(r * 3 + 3, r * 3 + 3) == "1" }
  end
  return rows
end

function M.has(ch) return G[ch] ~= nil or G[ch:upper()] ~= nil end

return M
